def run_sql(db, text, refused=None):
    """Run one statement from a file (payloads exceed a command line); verbose errors carry the SQLSTATE."""
    path = db.cluster.scratch / f'q{next(_counter)}.sql'
    path.write_text('\\set VERBOSITY verbose\n' + text + '\n')
    r = db.cluster.psql(db.name, ['-f', str(path)])
    if refused is not None:
        assert r.returncode != 0, f'expected refusal "{refused}" but succeeded: {text[:160]}'
        line = bs.error_line(r.stderr)
        assert refused in line, f'expected refusal "{refused}", got: {line[:300]}'
        return line
    assert r.returncode == 0, f'{text[:300]}\n{r.stderr[-800:]}'
    return r.stdout.strip()


def outcome(db, text):
    """The answer or the ERROR line (with its SQLSTATE), so two databases can be compared."""
    path = db.cluster.scratch / f'q{next(_counter)}.sql'
    path.write_text('\\set VERBOSITY verbose\n' + text + '\n')
    r = db.cluster.psql(db.name, ['-f', str(path)])
    return ('ok', r.stdout.strip()) if r.returncode == 0 else ('error', bs.error_line(r.stderr))


# ------------------------------------------------------------------ nodes
def card_id(card):
    return RANKS.index(card[0]) * 4 + SUITS.index(card[1])


def live(board, n=6):
    blocked = {card_id(board[i:i + 2]) for i in range(0, len(board), 2)}
    out = []
    for b in range(1, 52):
        for a in range(b):
            if a not in blocked and b not in blocked:
                out.append(b * (b - 1) // 2 + a)
    return out[:n]


def texture(db, board):
    return db.sql(f"SELECT public.fn_gto_texture_class_any({q(board)})")


def ctx(db, street, board, role, *, depth=200, pot_type='srp', facing='none', size='none', line=None, contract='v3'):
    c = {'street': street, 'game_family': 'cash', 'objective': 'cash_ev', 'utility_context': 'cash_ev', 'table_size': 2,
         'pot_type': pot_type, 'hero_position': 'BB', 'opponent_position': 'SB', 'depth_bucket': depth,
         'texture_class': texture(db, board), 'node_role': role, 'facing_kind': facing, 'facing_size_bucket': size}
    if line is not None:
        c.update(cell_contract=contract, line_class=line)
    return c


def node(cell, board, path, *, pot=650, aggressor=1, facing=(None, None), specs=None, seed=0, v4=False, **override):
    """A complete source node that the live validators accept (pio-policy v3, or v4 with state and ranges).
    The worker omits node_checksum; the ingest functions compute it."""
    specs = specs or (FACING if facing[0] is not None else OPEN)
    acts = list(specs)
    m, pev = [0.0] * 1326, [None] * 1326
    fr = {a: [0.0] * 1326 for a in acts}
    aev = {a: [None] * 1326 for a in acts}
    for k, i in enumerate(live(board)):
        f = ((k + seed) % 5) / 4
        m[i] = 1.0
        fr[acts[0]][i], fr[acts[1]][i] = 1 - f, f
        aev[acts[0]][i], aev[acts[1]][i] = 0.5, 0.25
        pev[i] = round((1 - f) * 0.5 + f * 0.25, 6)
    value = {'schema': 'smarter-poker.pio-policy.v4' if v4 else 'smarter-poker.pio-policy.v3', 'node': path,
             'node_context': {**cell, 'board': board, 'facing_target_chips': facing[0], 'facing_actor_total_chips': facing[1]},
             'line_proof': {'schema': 'smarter-poker.pio-line-proof.v1', 'manifest_checksum': rp.TREE, 'hero_solver_player': 0,
                            'preflop_aggressor_solver_player': aggressor, 'root_pot_chips': pot,
                            'effective_stack_chips': cell['depth_bucket'] * BB, 'chips_per_bb': BB},
             'action_specs': specs, 'frequencies': fr, 'policy_evs_bb': pev, 'action_evs_bb': aev, 'matchups': m,
             'source_combo_order_checksum': 'd' * 64, 'range_bundle_checksum': 'c' * 64}
    for path_, replacement in override.items():
        target, keys = value, path_.split('.')
        for key in keys[:-1]:
            target = target[key]
        target[keys[-1]] = replacement
    return value


def with_v4(db, value, state_fn):
    """Add the exact complete public state (as `state_fn` derives it) and exact node ranges."""
    blocked = {card_id(value['node_context']['board'][i:i + 2]) for i in range(0, len(value['node_context']['board']), 2)}
    ranges = [0.0 if (a in blocked or b in blocked) else 0.5 for b in range(1, 52) for a in range(b)]
    value = {**value, 'complete_public_state': {'utility': {'objective': 'cash_ev', 'utility_context': 'cash_ev', 'rake': [0, 0],
                                                             'icm_model_bundle_checksum': 'e' * 64, 'icm_model': None}},
             'solver_ranges': {'schema': 'smarter-poker.pio-exact-node-ranges.v1', 'OOP': ranges, 'IP': ranges}}
    state = run_sql(db, f"SELECT public.{state_fn}({qj(value)})")
    assert state, f'{state_fn} derived no state for {value["node"]}'
    value['complete_public_state'] = json.loads(state)
    return value


def artifact(tag, street, depth, nodes, m2_receipt=False):
    h = hashlib.sha256(tag.encode()).hexdigest()
    matrix = {'schema': 'smarter-poker.pio-artifact.v31.1', 'combo_order': COMBO_ORDER, 'nodes': nodes}
    if m2_receipt:
        matrix.update(selection_receipt={'fixture': tag}, selection_receipt_checksum=hashlib.sha256(('r' + tag).encode()).hexdigest())
    return {'id': f'{h[:8]}-{h[8:12]}-4{h[13:16]}-8{h[17:20]}-{h[20:32]}', 'scenario_hash': 'scen-' + h[:24],
            'game_family': 'cash', 'stack_depth': depth, 'street': street, 'solved_at': SOLVED_AT, 'strategy_matrix_v2': matrix}


def ingest(db, ds, machine, art, fn='fn_gto_v31_ingest_source_artifact'):
    return f"SELECT public.{fn}({q(ds)},{q(machine)},{qj(art)})"


def rows(db, ds):
    """Every gold and source-artifact row of the dataset, timestamps written by the clock excluded."""
    return db.sql("SELECT coalesce(jsonb_agg(x ORDER BY x::text),'[]') FROM ("
                  "SELECT to_jsonb(a)-'ingested_at' x FROM gto_v31_source_artifacts a WHERE a.dataset_id=" + q(ds) +
                  " UNION ALL SELECT to_jsonb(s)-'audited_at'-'created_at' FROM solved_spots_gold s WHERE s.id IN "
                  "(SELECT source_row_id FROM gto_v31_source_artifacts WHERE dataset_id=" + q(ds) + ")) t")


def dataset(db, key, declared, schema=None):
    return bs.dataset(db, key, declared, schema=schema, replica=True)


def direct_row(ds, row, depth, tag):
    """A gold row (written as the ingest functions write it, triggers aside) and its source-artifact row."""
    return ("BEGIN; SET LOCAL session_replication_role=replica; "
            "INSERT INTO solved_spots_gold(id,scenario_hash,strategy_matrix_v2,solver_version,solver_binary_checksum,machine_id,"
            "pipeline_commit,manifest_version,manifest_checksum,source_artifact_checksum,quality_status,audited_at,pipeline_bundle_checksum) "
            f"VALUES ({q(row)},{q(tag)},'{{}}','pio-3',repeat('1',64),'M1',repeat('2',40),'m1',{q(rp.TREE)},repeat('a',64),'validated',now(),repeat('3',64)); COMMIT; "
            "INSERT INTO gto_v31_source_artifacts(dataset_id,source_row_id,machine_id,scenario_hash,game_family,stack_depth,"
            f"street,source_artifact_checksum,node_count,solved_at) VALUES ({q(ds)},{q(row)},'M1',{q(tag)},'cash',{depth},"
            f"'flop',repeat('a',64),1,{q(SOLVED_AT)}) RETURNING stack_depth")


