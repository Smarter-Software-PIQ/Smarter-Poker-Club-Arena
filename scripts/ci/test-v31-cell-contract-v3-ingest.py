def line_vectors(old, new):
    doc = json.loads((FIX / '01-line-vectors.json').read_text())
    vec = doc['vectors']  # [node, pot, stack, aggressor, line_class_v3, analyze_node v3, analyze_node v2]
    payload = [{'n': v[0], 'p': v[1], 's': v[2], 'a': v[3]} for v in vec]
    v3calls = ("public.fn_gto_v31_node_line_class_v3(x->>'n',(x->>'p')::numeric,(x->>'s')::numeric),"
               "public.fn_gto_v31_node_line_proof_v3(x->>'n',(x->>'a')::integer,(x->>'p')::numeric,(x->>'s')::numeric),")
    sql = ("SELECT jsonb_agg(jsonb_build_array(" + v3calls +
           "public.fn_gto_v31_node_line_proof(x->>'n',(x->>'a')::integer,(x->>'p')::numeric,(x->>'s')::numeric)) ORDER BY o) "
           f"FROM jsonb_array_elements({qj(payload)}) WITH ORDINALITY e(x,o)")
    got = json.loads(run_sql(new, sql))
    v2_old = json.loads(run_sql(old, sql.replace(v3calls, '')))
    def shape(p):
        return None if p is None else [p['street'], p['current_actor_solver_player'], p['derived_node_role'], p['derived_facing_kind'],
                                       p['derived_facing_size_bucket'], p['facing_target_chips'], p['facing_actor_total_chips']]
    bad = []
    for v, (line, p3, p2), (p2_old,) in zip(vec, got, v2_old):
        if line != v[4]:
            bad.append(('line', v[:3], line, v[4]))
        if shape(p3) != v[5]:
            bad.append(('v3', v[:4], shape(p3), v[5]))
        if shape(p2) != v[6] or p2 != p2_old:
            bad.append(('v2', v[:4], shape(p2), v[6]))
        if p2 is not None and p3 != p2:
            bad.append(('v3 differs where v2 proves', v[:4]))
    assert not bad, f'{len(bad)} of {len(vec)} vectors differ, first: {bad[:3]}'
    assert sum(1 for v in vec if v[5] and v[5][2] == 'donk') >= 50 and sum(1 for v in vec if v[5] and v[5][4] == 'big') >= 50
    return len(vec), doc['source']['commit'][:12]


