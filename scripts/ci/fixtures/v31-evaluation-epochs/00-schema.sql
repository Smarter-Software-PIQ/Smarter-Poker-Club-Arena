  CONSTRAINT gto_v31_release_evaluations_dataset_checksum_check CHECK (((dataset_checksum ~ '^[0-9a-f]{64}$'::text) AND (dataset_checksum <> repeat('0'::text, 64)))),
  CONSTRAINT gto_v31_release_evaluations_dataset_id_evaluation_kind_game_key UNIQUE (dataset_id, evaluation_kind, game_family),
