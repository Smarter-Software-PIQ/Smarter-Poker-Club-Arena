CREATE FUNCTION public.fn_gto_v31_freeze_evaluation_source() RETURNS trigger LANGUAGE plpgsql
  SECURITY DEFINER SET search_path TO 'public' AS $function$
BEGIN
  IF EXISTS (SELECT 1 FROM public.gto_v31_release_evaluations e WHERE e.source_result_id=OLD.id) THEN
    RAISE EXCEPTION 'a league result used as certified solver evidence is immutable';
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$function$;
CREATE TRIGGER gto_v31_evaluation_source_is_immutable BEFORE DELETE OR UPDATE ON public.horse_league_results
  FOR EACH ROW EXECUTE FUNCTION fn_gto_v31_freeze_evaluation_source();

