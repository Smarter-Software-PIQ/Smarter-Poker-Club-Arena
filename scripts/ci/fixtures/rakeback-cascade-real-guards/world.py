"""Builds the fixture world SQL from the production catalog readouts (shared by the harness)."""
import json,re
WIRED_FULL=['chip_ledger','agents','settlement_invoices','rakeback_period_payouts','rakeback_periods','wallet_transactions','chip_transactions',
 'accounting_rakeback_period_calculations','accounting_rakeback_payer_contracts','accounting_rakeback_wallet_contracts','accounting_rakeback_wallet_transfers',
 'accounting_rakeback_payer_transfers','accounting_routed_settlement_runs','chip_ledger_idem','union_wallets','accounting_agreement_history','profiles_none']
WIRED_UPDATE=['clubs','club_members']
# INSERT-only production triggers wired on purpose (the nightly treasury reconciliation reads what this one records).
WIRED_EXTRA={('public.clubs','trg_ca_club_gets_a_baseline')}
def qi(s): return '"'+s.replace('"','""')+'"'
def events(tdef):
    m=re.search(r'\b(BEFORE|AFTER|INSTEAD OF) (.*?) ON (?:public|smarter_private)\.',tdef,re.S)
    return m.group(2)
def tables_sql(rel):
    seqs=[];tabs=[];defaults=[];cons=[];idx=[];views=[];dropped_fk=[]
    for k in sorted(rel):
        x=rel[k];fq=f"{x['s']}.{qi(x['t'])}"
        if x['kind']=='S':
            seqs.append(f"CREATE SEQUENCE {fq} AS {x['seq']['ty']} START {x['seq']['start']} INCREMENT {x['seq']['inc']};");continue
        if x['kind'] in('v','m'):
            views.append((k,f"CREATE VIEW {fq} AS {x['view']}"));continue
        cols=[]
        for c in x['cols']:
            s=f"{qi(c['n'])} {c['ty']}"
            if c['gen']=='s': s+=f" GENERATED ALWAYS AS ({c['def']}) STORED"
            elif c['ident']=='a': s+=" GENERATED ALWAYS AS IDENTITY"
            elif c['ident']=='d': s+=" GENERATED BY DEFAULT AS IDENTITY"
            elif c['def'] is not None: defaults.append(f"ALTER TABLE {fq} ALTER COLUMN {qi(c['n'])} SET DEFAULT {c['def']};")
            if c['nn'] and not c['ident']: s+=" NOT NULL"
            cols.append(s)
        tabs.append(f"CREATE TABLE {fq}({','.join(cols)});")
        for c in x['cons'] or []:
            if c['ty']=='f': dropped_fk.append((k,c['n'],c['def']));continue
            if c['ty']=='t': continue
            if c['ty']=='n': continue
            cons.append((0 if c['ty'] in 'pu' else 1,f"ALTER TABLE {fq} ADD CONSTRAINT {qi(c['n'])} {c['def']};"))
        for i in x['idx'] or []: idx.append(i+';')
    have={k for k in rel if rel[k]['kind']=='S'}
    for d in defaults:
        for n in re.findall(r"nextval\('([a-z_0-9.\"]+)'::regclass\)",d):
            fqn=n if '.' in n else 'public.'+n
            if fqn not in have: have.add(fqn); seqs.append(f'CREATE SEQUENCE {fqn};')
    return seqs,tabs,defaults,[c for _,c in sorted(cons,key=lambda z:z[0])],idx,views,dropped_fk
def triggers(rel):
    wired=[];skipped=[]
    for k in sorted(rel):
        x=rel[k]
        for t in x['trg'] or []:
            full=x['s']=='public' and x['t'] in WIRED_FULL
            upd=x['s']=='public' and x['t'] in WIRED_UPDATE and 'UPDATE' in events(t['def'])
            if full or upd or (k,t['n']) in WIRED_EXTRA:
                sql=t['def']+';'
                if t['e']=='A': sql+=f"\nALTER TABLE {x['s']}.{qi(x['t'])} ENABLE ALWAYS TRIGGER {qi(t['n'])};"
                elif t['e']!='O': raise SystemExit(('unexpected trigger state',k,t['n'],t['e']))
                wired.append({'table':k,'name':t['n'],'function':t['f'],'function_md5':t['fm'],'sql':sql})
            else: skipped.append({'table':k,'name':t['n'],'function':t['f'],'events':events(t['def'])})
    return wired,skipped
