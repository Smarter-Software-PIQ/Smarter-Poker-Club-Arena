#!/usr/bin/env python3
"""Run the maintained stall-ingest transition in a private PostgreSQL 17 cluster."""
import json
import os
from datetime import datetime
from pathlib import Path
import re
import shlex
import shutil
import socket
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
MIGRATIONS = ROOT / 'supabase/migrations'
pg_bin = Path(os.environ.get('PG_BIN', '/opt/homebrew/opt/postgresql@17/bin'))
if not (pg_bin / 'initdb').exists():
    pg_bin = Path('/usr/lib/postgresql/17/bin')

def run(args, **kwargs):
    return subprocess.run([str(a) for a in args], check=True, text=True,
                          capture_output=True, timeout=60, **kwargs).stdout

assert re.search(r'PostgreSQL\) 17\.', run([pg_bin/'initdb', '--version']))
patches = list(MIGRATIONS.glob('*_stall_progress_requires_a_recorded_hand.sql'))
assert len(patches) == 1, patches
sustained = list(MIGRATIONS.glob('*_stall_recovery_needs_sustained_dealing.sql'))
assert len(sustained) == 1, sustained

with tempfile.TemporaryDirectory(prefix='stall-proof-', dir=os.environ.get('TMPDIR')) as scratch:
    scratch = Path(scratch)
    data = scratch/'pg'
    run([pg_bin/'initdb', '-D', data, '-A', 'trust', '-U', 'fixture_owner', '--no-locale'])
    with socket.socket() as sock:
        sock.bind(('127.0.0.1', 0)); port = sock.getsockname()[1]
    options = shlex.join(['-F', '-h', '127.0.0.1', '-p', str(port), '-c', 'unix_socket_directories='])
    started = False
    def sql(statement):
        return run([pg_bin/'psql', '-X', '-qAt', '-v', 'ON_ERROR_STOP=1', '-h', '127.0.0.1',
                    '-p', str(port), '-U', 'fixture_owner', '-d', 'postgres'], input=statement).strip()
    try:
        run([pg_bin/'pg_ctl', '-D', data, '-l', scratch/'pg.log', '-o', options, '-w', 'start'])
        started = True
        initial = (MIGRATIONS/'20261031182341_a_stopped_table_is_caught_in_sixty_seconds.sql').read_text()
        source = (MIGRATIONS/'20261031190452_stall_watch_knows_waits_staleness_and_custody.sql').read_text()
        sql('CREATE SCHEMA smarter_private;\n'+initial.split('REVOKE ALL', 1)[0])
        sql(source.split('CREATE OR REPLACE FUNCTION', 1)[0])
        sql('''CREATE TABLE public.operational_alert_events (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          source text,event_key text,alertname text,status text,severity text,payload jsonb,
          last_received_at timestamptz,UNIQUE(source,event_key));
        CREATE TABLE public.hand_history(id uuid PRIMARY KEY,table_id uuid,created_at timestamptz);
        CREATE INDEX ON public.hand_history(table_id,created_at,id);
        CREATE TABLE smarter_private.tournament_abort_targets
          (tournament_id uuid,requested_at timestamptz,operation_id uuid,settled_at timestamptz);
        CREATE TABLE public.tournament_players(tournament_id uuid,user_id uuid,status text);
        CREATE TABLE public.profiles(id uuid,is_horse boolean);''')
        for name in ['fn_ca_table_stall_watch_failed', 'fn_ca_table_stall_watch_ingest']:
            match = re.search(r'CREATE OR REPLACE FUNCTION public\.'+name+r'\(.*?\$function\$;', source, re.S)
            assert match, name
            sql(match.group(0))
        for filename in ['20261031190637_stall_watch_restart_is_not_stale.sql',
                         '20261031202225_stall_watch_maintenance_is_bounded.sql']:
            sql((MIGRATIONS/filename).read_text())

        table = '11111111-1111-4111-8111-111111111111'
        foreign = '22222222-2222-4222-8222-222222222222'
        hand = '33333333-3333-4333-8333-333333333333'
        detected = '2026-11-01T13:10:00Z'
        now = '2026-11-01T13:11:00Z'
        metrics = '\npoker_fleet_tables_stalled 0\npoker_uptime_seconds 1000\npoker_engine_info{instance_id="fixture"} 1\npoker_active_tables 1\npoker_maintenance_break_active 0\n'
        def seed(detection=detected):
            sql(f'''TRUNCATE operational_alert_events,hand_history,smarter_private.ca_table_stall_watch;
            UPDATE smarter_private.ca_table_stall_watch_state SET last_uptime_s=NULL,last_instance=NULL,
              stop_alert_id=NULL,blind_alert_id=NULL,maint_since=NULL;
            INSERT INTO operational_alert_events(id,source,event_key,alertname,status,severity,payload)
              VALUES(1,'ca-stall-watch','episode','TableStoppedDealing','firing','critical',
              jsonb_build_object('table_id','{table}','detected_at','{detection}'));
            INSERT INTO smarter_private.ca_table_stall_watch
              (table_id,first_seen_at,last_seen_at,ms_since_progress,alert_id,people_waiting)
              VALUES('{table}','2026-11-01T13:00:00Z','{detected}',600000,1,true);''')
        def ingest():
            sql("SELECT public.fn_ca_table_stall_watch_ingest($metrics$"+metrics+"$metrics$, '"+now+"',60000);")
        def state():
            return json.loads(sql("SELECT jsonb_build_object('status',status,'payload',payload,'watch_count',(SELECT count(*) FROM smarter_private.ca_table_stall_watch)) FROM operational_alert_events WHERE id=1;"))
        results = []
        seed(); ingest()
        assert state()['status'] == 'resolved', 'counterfactual no longer reproduces; inspect baseline'
        results.append('before: absent table falsely resolves without a hand')
        sql(patches[0].read_text())
        for case,hand_table,at,detection in [
            ('absent table',None,None,detected),
            ('foreign hand',foreign,'2026-11-01T13:10:30Z',detected),
            ('old hand',table,'2026-11-01T13:09:59Z',detected),
            ('future hand',table,'2026-11-01T13:11:01Z',detected),
            ('missing detection',table,'2026-11-01T13:10:30Z',''),
        ]:
            seed(detection)
            if hand_table:
                sql(f"INSERT INTO hand_history VALUES('{hand}','{hand_table}','{at}');")
            ingest(); actual = state()
            assert actual['status'] == 'firing' and actual['watch_count'] == 1, (case,actual)
            assert 'progress_hand_id' not in actual['payload'], actual
            results.append('after: '+case+' preserves alert and watch')
        seed()
        sql(f"INSERT INTO hand_history VALUES('{hand}','{table}','2026-11-01T13:10:30Z');")
        ingest(); actual = state()
        assert actual['status'] == 'resolved' and actual['watch_count'] == 0, actual
        assert actual['payload']['progress_hand_id'] == hand, actual
        assert datetime.fromisoformat(actual['payload']['progress_hand_at']) == datetime.fromisoformat('2026-11-01T13:10:30+00:00'), actual
        results.append('after: exact recorded hand closes once and retains witness')
        sql("UPDATE smarter_private.ca_table_stall_watch_state SET last_uptime_s=NULL;")
        ingest()
        assert state() == actual, 'duplicate observation changed the closure receipt'
        results.append('after: duplicate observation preserves the receipt')
        # Keep the installed original body after a refused reapplication.
        before = sql("SELECT md5(prosrc) FROM pg_proc WHERE oid='public.fn_ca_table_stall_watch_ingest(text,timestamptz,bigint)'::regprocedure;")
        try:
            sql(patches[0].read_text())
            raise AssertionError('unexpected duplicate migration acceptance')
        except subprocess.CalledProcessError as error:
            assert 'expected exactly one' in error.stderr, error.stderr
        assert sql("SELECT md5(prosrc) FROM pg_proc WHERE oid='public.fn_ca_table_stall_watch_ingest(text,timestamptz,bigint)'::regprocedure;") == before
        results.append('after: duplicate migration refuses atomically')
        # A single completed hand is progress, but cannot certify continued dealing.
        # Exercise the same maintained ingest entry point, not a mirrored predicate.
        sql(sustained[0].read_text())
        for case, times in [
            ('one hand only', ['2026-11-01T13:10:30Z']),
            ('two stale hands', ['2026-11-01T13:10:01Z', '2026-11-01T13:10:02Z']),
            ('second hand outside episode', ['2026-11-01T13:09:59Z', '2026-11-01T13:10:50Z']),
        ]:
            seed()
            for index, at in enumerate(times):
                sql(f"INSERT INTO hand_history VALUES('33333333-3333-4333-8333-{index+1:012d}','{table}','{at}');")
            # Existing detection threshold is 60 seconds; exercise a later observation
            # so the stale pair is outside that same bounded liveness window.
            observation = '2026-11-01T13:12:00Z' if case == 'two stale hands' else now
            sql("SELECT public.fn_ca_table_stall_watch_ingest($metrics$"+metrics+"$metrics$, '"+observation+"',60000);")
            assert state()['status'] == 'firing' and state()['watch_count'] == 1, (case,state())
            results.append('sustained: '+case+' preserves original episode')
        seed()
        sql(f"INSERT INTO hand_history VALUES('{hand}','{table}','2026-11-01T13:10:20Z'),('44444444-4444-4444-8444-444444444444','{table}','2026-11-01T13:10:50Z');")
        ingest(); actual = state()
        assert actual['status'] == 'resolved' and actual['watch_count'] == 0, actual
        assert actual['payload']['progress_hand_id'] == '44444444-4444-4444-8444-444444444444', actual
        assert actual['payload']['previous_progress_hand_id'] == hand, actual
        assert actual['payload']['root_cause_verified'] is False, actual
        assert actual['payload']['resolution'] == 'recorded dealing resumed; root cause unverified', actual
        results.append('sustained: two exact episode hands retain both witnesses, never certify root cause')
        sql("UPDATE smarter_private.ca_table_stall_watch_state SET last_uptime_s=NULL;")
        ingest()
        assert state() == actual, 'duplicate observation replaced sustained witness'
        results.append('sustained: duplicate observation retains original recovery receipt')
        seed()
        sql(f"INSERT INTO hand_history VALUES('{hand}','{table}','2026-11-01T13:10:50Z'),('44444444-4444-4444-8444-444444444444','{foreign}','2026-11-01T13:10:40Z');")
        ingest()
        assert state()['status'] == 'firing', state()
        results.append('sustained: another table cannot supply the second witness')
        # The intended wait is explanatory evidence, never proof a firing table resumed.
        sql('''CREATE FUNCTION public.fn_ca_table_stall_facts(uuid,uuid[],timestamptz)
          RETURNS jsonb LANGUAGE sql AS $$ SELECT '{"people_waiting":true}'::jsonb $$;
        CREATE FUNCTION public.fn_ca_table_stall_decide(jsonb,bigint,timestamptz,boolean,boolean)
          RETURNS text LANGUAGE sql AS $$ SELECT 'tournament_break'::text $$;''')
        seed()
        waiting_metrics = metrics + f'poker_table_ms_since_progress{{table_id="{table}",paused="1"}} 600000\n'
        sql("SELECT public.fn_ca_table_stall_watch_ingest($metrics$"+waiting_metrics+"$metrics$, '"+now+"',60000);")
        actual = state()
        assert actual['status'] == 'firing' and actual['watch_count'] == 1, actual
        assert actual['payload']['intended_wait_reason'] == 'tournament_break', actual
        assert actual['payload']['root_cause_verified'] is False, actual
        assert sql('SELECT alert_id FROM smarter_private.ca_table_stall_watch;') == '1'
        results.append('sustained: intended wait preserves firing status, identity and watch')
        before = sql("SELECT md5(prosrc) FROM pg_proc WHERE oid='public.fn_ca_table_stall_watch_ingest(text,timestamptz,bigint)'::regprocedure;")
        try:
            sql(sustained[0].read_text())
            raise AssertionError('unexpected sustained migration replay')
        except subprocess.CalledProcessError as error:
            assert 'missing original' in error.stderr, error.stderr
        assert sql("SELECT md5(prosrc) FROM pg_proc WHERE oid='public.fn_ca_table_stall_watch_ingest(text,timestamptz,bigint)'::regprocedure;") == before
        results.append('sustained: replay refuses atomically without changing installed source')
        print(json.dumps({'status':'passed','checks':results,'postgres':run([pg_bin/'postgres','--version']).strip()}))
    finally:
        if started:
            run([pg_bin/'pg_ctl','-D',data,'-m','immediate','-w','stop'])
