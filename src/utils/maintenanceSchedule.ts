/** Heads-up only. The engine's actual maintenance event owns freeze/release. */
import ownerMaintenanceNotices from './ownerMaintenanceNotices.json';
export const PHASE1_MAINTENANCE_POLICY_ID = 'phase1-hourly-01a1944f';
export type RoutineMaintenanceSchedule = 'daily' | 'phase1-hourly' | 'unknown';

/** Validate the serving protocol, never the desired source policy's active/off flag. */
export function observedMaintenanceSchedule(value: unknown): RoutineMaintenanceSchedule {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return 'unknown';
  const schedule = value as Record<string, unknown>;
  if (
    schedule.timeZone !== 'America/Chicago' ||
    schedule.startMinute !== 0 ||
    schedule.durationMs !== 300000 ||
    typeof schedule.nextAnnouncementAt !== 'number' ||
    !Number.isFinite(schedule.nextAnnouncementAt) ||
    schedule.nextAnnouncementAt <= 0
  )
    return 'unknown';
  const legacy = schedule.frequency === undefined && schedule.policyId === undefined;
  const known = schedule.policyId === PHASE1_MAINTENANCE_POLICY_ID;
  if (
    (legacy || (known && schedule.frequency === 'daily')) &&
    schedule.startHour === 4 &&
    schedule.hourlyCashFreeze === false
  )
    return 'daily';
  if (
    known &&
    schedule.frequency === 'phase1-hourly' &&
    schedule.startHour === null &&
    schedule.hourlyCashFreeze === true
  )
    return 'phase1-hourly';
  return 'unknown';
}

const chicagoClock = new Intl.DateTimeFormat('en-US', {
  timeZone: 'America/Chicago',
  hour: '2-digit',
  minute: '2-digit',
  hourCycle: 'h23',
});
export function isRoutineMaintenanceUpcoming(
  at: number,
  schedule: RoutineMaintenanceSchedule = 'daily'
): boolean {
  if (!Number.isFinite(at) || schedule === 'unknown') return false;
  const parts = chicagoClock.formatToParts(at);
  const hour = Number(parts.find((part) => part.type === 'hour')?.value);
  const minute = Number(parts.find((part) => part.type === 'minute')?.value);
  return (schedule === 'phase1-hourly' || hour === 3) && minute >= 55 && minute < 58;
}

/* ── BOOKED WINDOW NOTICE (Dan 2026-11-07) ────────────────────────────────
   An owner maintenance window booked outside the 04:00 daily window used to
   reach players only as the engine's two-minute last-hand warning: the
   Horse fold provenance cutover was booked at 13:13 Chicago and froze entry
   at 13:16, and the owner's own Lightning joins were refused. Every booked
   window is now projected into ownerMaintenanceNotices.json (generated by
   scripts/generate-owner-maintenance-notices.mjs) and every new one must
   carry playerNoticeAt at least 20 minutes before notBefore
   (tests/a-booked-window-gives-players-notice.law.test.ts), so the banner can
   say a short break is coming before it does. Heads-up only: the engine's
   actual maintenance event still owns freeze and release. */

export interface BookedMaintenanceNotice {
  id: string;
  kind: 'engine' | 'database';
  /** When players may first be told; windows booked before 2026-11-07 21:00 UTC have none. */
  noticeAtMs: number | null;
  notBeforeMs: number;
  notAfterMs: number;
}

/** A window with no playerNoticeAt is shown from one hour before notBefore. */
export const BOOKED_NOTICE_DEFAULT_LEAD_MS = 60 * 60 * 1000;

function parseBooked(raw: unknown): BookedMaintenanceNotice[] {
  const list = (raw as { notices?: unknown })?.notices;
  if (!Array.isArray(list)) return [];
  const out: BookedMaintenanceNotice[] = [];
  for (const row of list) {
    const r = row as Record<string, unknown>;
    const notBeforeMs = Date.parse(String(r.notBefore));
    const notAfterMs = Date.parse(String(r.notAfter));
    const noticeAtMs = typeof r.noticeAt === 'string' ? Date.parse(r.noticeAt) : null;
    if (
      typeof r.id !== 'string' ||
      (r.kind !== 'engine' && r.kind !== 'database') ||
      !Number.isFinite(notBeforeMs) ||
      !Number.isFinite(notAfterMs) ||
      notAfterMs <= notBeforeMs ||
      (noticeAtMs !== null && !Number.isFinite(noticeAtMs))
    )
      continue;
    out.push({ id: r.id, kind: r.kind, noticeAtMs, notBeforeMs, notAfterMs });
  }
  return out;
}

export const BOOKED_MAINTENANCE_NOTICES: readonly BookedMaintenanceNotice[] =
  parseBooked(ownerMaintenanceNotices);

/** The booked window players should be told about at `at`, or null. Earliest start wins. */
export function bookedMaintenanceNotice(
  at: number,
  notices: readonly BookedMaintenanceNotice[] = BOOKED_MAINTENANCE_NOTICES
): BookedMaintenanceNotice | null {
  if (!Number.isFinite(at)) return null;
  let best: BookedMaintenanceNotice | null = null;
  for (const n of notices) {
    const from = n.noticeAtMs ?? n.notBeforeMs - BOOKED_NOTICE_DEFAULT_LEAD_MS;
    if (at < from || at >= n.notAfterMs) continue;
    if (!best || n.notBeforeMs < best.notBeforeMs) best = n;
  }
  return best;
}

const chicagoTime = new Intl.DateTimeFormat('en-US', {
  timeZone: 'America/Chicago',
  hour: 'numeric',
  minute: '2-digit',
  hour12: true,
});
const chicagoDay = new Intl.DateTimeFormat('en-US', {
  timeZone: 'America/Chicago',
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
});
const chicagoWeekday = new Intl.DateTimeFormat('en-US', {
  timeZone: 'America/Chicago',
  weekday: 'long',
});

/** "1:15 PM", "Tomorrow 1:15 PM" or "Monday 1:15 PM", relative to `at` in Chicago. */
export function chicagoNoticeTime(ms: number, at: number): string {
  const time = chicagoTime.format(ms);
  const day = chicagoDay.format(ms);
  if (day === chicagoDay.format(at)) return time;
  if (day === chicagoDay.format(at + 24 * 60 * 60 * 1000)) return `Tomorrow ${time}`;
  return `${chicagoWeekday.format(ms)} ${time}`;
}

/**
 * The banner sentence for a booked window (Title Case, no em dashes). Before
 * the window opens it names the window; once open, it says a break can start
 * any time before the window closes, because an earliest-certified cutover
 * starts when its release is certified, not at a fixed minute.
 */
export function bookedMaintenanceNoticeText(notice: BookedMaintenanceNotice, at: number): string {
  const until = chicagoNoticeTime(notice.notAfterMs, at);
  if (at < notice.notBeforeMs) {
    return `Short Maintenance Break Possible Between ${chicagoNoticeTime(notice.notBeforeMs, at)} And ${until} Chicago Time. Play Pauses For About Five Minutes.`;
  }
  return `A Short Maintenance Break Can Start Any Time Before ${until} Chicago Time. Play Pauses For About Five Minutes.`;
}
