/**
 * Generates server/src/engine/HorseHoldemPreflopClassEquity.data.ts: the 169 x 169 preflop all-in equity of each
 * hold'em starting-hand class against each other class (hero row, villain column; a tie counts half), used by the
 * Hold'em tournament raise-defence price (HorseHoldemTournamentRaiseDefence.ts) so that no equity is sampled while a
 * Horse decides.
 *
 * Method: for each unordered pair of classes, every card-compatible pair of combos is enumerated and the boards are
 * dealt round-robin over those combo pairs from a fixed xorshift stream (seed below), BOARDS_PER_PAIR boards per class
 * pair, scored with the engine's own evaluator (HorseEval.scoreHoldemPlus2Ids). The stream is used only here, offline;
 * the table it writes is a constant. Standard error per cell is about 0.5 equity points at 10,000 boards.
 *
 * Run from server/: npx tsx scripts/holdem-preflop-class-equity-gen.ts [boardsPerPair]
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import type { Card, CardRank, CardSuit } from '../src/types.js';
import { holdemCardId, packHoldemBoardBits, scoreHoldemPlus2Ids } from '../src/engine/HorseEval.js';
import { NASH_PUSH_FOLD_V2 } from '../src/engine/HorseNashPushFoldV2.data.js';

const BOARDS_PER_PAIR = Number(process.argv[2] ?? 10000);
const SEED = 0x20261124;
const VERSION = 'holdem-preflop-class-equity-v1';
const CLASSES: readonly string[] = NASH_PUSH_FOLD_V2.classes;
const RANKS = 'AKQJT98765432';
const SUITS: readonly CardSuit[] = ['hearts', 'diamonds', 'clubs', 'spades'];

const deckId = (r: number, s: number) => r * 4 + s;
const DECK: Card[] = [];
for (let r = 0; r < 13; r++)
  for (let s = 0; s < 4; s++) DECK.push({ rank: RANKS[r] as CardRank, suit: SUITS[s] });
const EVAL = DECK.map((c) => holdemCardId(c));

function combos(cls: string): Array<[number, number]> {
  const r1 = RANKS.indexOf(cls[0]);
  const r2 = RANKS.indexOf(cls[1]);
  const out: Array<[number, number]> = [];
  if (cls.length === 2) {
    for (let i = 0; i < 4; i++)
      for (let j = i + 1; j < 4; j++) out.push([deckId(r1, i), deckId(r2, j)]);
  } else if (cls.endsWith('s')) {
    for (let s = 0; s < 4; s++) out.push([deckId(r1, s), deckId(r2, s)]);
  } else {
    for (let a = 0; a < 4; a++)
      for (let b = 0; b < 4; b++) if (a !== b) out.push([deckId(r1, a), deckId(r2, b)]);
  }
  return out;
}
const COMBOS = CLASSES.map(combos);

let state = SEED >>> 0;
function next(): number {
  state ^= state << 13;
  state >>>= 0;
  state ^= state >>> 17;
  state ^= state << 5;
  state >>>= 0;
  return state;
}

const bits = {
  once: 0,
  twice: 0,
  thrice: 0,
  four: 0,
  sm0: 0,
  sm1: 0,
  sm2: 0,
  sm3: 0,
  sc0: 0,
  sc1: 0,
  sc2: 0,
  sc3: 0,
  count: 0,
};
const board = new Uint8Array(5);
const used = new Uint8Array(52);
const eq = new Float64Array(169 * 169);
const t0 = Date.now();
for (let i = 0; i < 169; i++) {
  for (let j = i; j < 169; j++) {
    const pairs: Array<[number, number, number, number]> = [];
    for (const [a, b] of COMBOS[i])
      for (const [c, d] of COMBOS[j])
        if (a !== c && a !== d && b !== c && b !== d) pairs.push([a, b, c, d]);
    let share = 0;
    for (let k = 0; k < BOARDS_PER_PAIR; k++) {
      const [a, b, c, d] = pairs[k % pairs.length];
      used.fill(0);
      used[a] = used[b] = used[c] = used[d] = 1;
      for (let n = 0; n < 5; n++) {
        let id: number;
        do id = next() % 52;
        while (used[id]);
        used[id] = 1;
        board[n] = EVAL[id];
      }
      packHoldemBoardBits(board, 5, bits as never);
      const h = scoreHoldemPlus2Ids(bits as never, EVAL[a], EVAL[b], false);
      const v = scoreHoldemPlus2Ids(bits as never, EVAL[c], EVAL[d], false);
      share += h > v ? 1 : h === v ? 0.5 : 0;
    }
    const e = share / BOARDS_PER_PAIR;
    eq[i * 169 + j] = i === j ? 0.5 : e;
    eq[j * 169 + i] = i === j ? 0.5 : 1 - e;
  }
  if (i % 20 === 0) process.stderr.write(`row ${i} ${((Date.now() - t0) / 1000).toFixed(0)}s\n`);
}
const u16 = new Uint16Array(169 * 169);
for (let k = 0; k < u16.length; k++) u16[k] = Math.round(eq[k] * 65535);
const b64 = Buffer.from(u16.buffer).toString('base64');
const lines: string[] = [];
for (let k = 0; k < b64.length; k += 100) lines.push(`  '${b64.slice(k, k + 100)}',`);
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(
  join(here, '..', 'src', 'engine', 'HorseHoldemPreflopClassEquity.data.ts'),
  `/**
 * GENERATED by server/scripts/holdem-preflop-class-equity-gen.ts (${BOARDS_PER_PAIR} boards per class pair, seed
 * 0x${SEED.toString(16)}). Do not edit by hand. The 169 x 169 preflop all-in equity of the row class against the
 * column class (ties half), in the class order of HorseNashPushFoldV2.data (NASH_PUSH_FOLD_V2.classes), as
 * little-endian uint16 (equity x 65535), base64.
 */
export const HOLDEM_PREFLOP_CLASS_EQUITY_VERSION = '${VERSION}' as const;
export const HOLDEM_PREFLOP_CLASS_EQUITY_BOARDS_PER_PAIR = ${BOARDS_PER_PAIR};
export const HOLDEM_PREFLOP_CLASS_EQUITY_U16_BASE64: string = [
${lines.join('\n')}
].join('');
`
);
process.stderr.write(`done ${((Date.now() - t0) / 1000).toFixed(0)}s\n`);
