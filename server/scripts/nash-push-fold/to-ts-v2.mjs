// Wraps `python3 -I solve.py equity169.tsv --v2` output as the engine's data
// module (the engine image emits with noResolve and lists its JSON resources
// explicitly, so a JSON import would not ship; see V71).
//
//   node to-ts-v2.mjs /tmp/nash-v2.json > ../../src/engine/HorseNashPushFoldV2.data.ts
//   npx prettier --write ../../src/engine/HorseNashPushFoldV2.data.ts
import { readFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const tables = {};
for (const key of Object.keys(src.tables).sort()) {
  const t = src.tables[key];
  tables[key] = { jam: t.jam, call: t.call };
}
const data = {
  model: src.model,
  depthGrid: src.depthGrid,
  classes: src.classes,
  alphabet: src.alphabet,
  bubbleLevels: src.bubbleLevels,
  tables,
};
process.stdout.write(`/**
 * Nash push/fold V2 (2026-11-07): jam AND call thresholds, 1..9 players
 * behind, dead ante 0/1/2bb, bubble factor 1/1.5/2/3. GENERATED by
 * server/scripts/nash-push-fold/solve.py --v2, wrapped by to-ts-v2.mjs (then
 * prettier); do not hand-edit. Reader, model and provenance:
 * HorseNashPushFoldV2.ts and docs/changelog/2026-11-07-nash-push-fold-v2.md.
 *
 * tables["<players behind the jammer>|<dead ante bb>|<bubble factor>"]:
 * jam / call.{open,sb,bb} are one character per class (classes order);
 * alphabet.indexOf(ch) / 2 is the deepest depth (bb, blind included) at
 * which the class still jams / calls; 0 is never.
 */
export type NashPushFoldV2Table = { jam: string; call: { open?: string; sb?: string; bb: string } };
export type NashPushFoldV2Data = {
  model: string;
  depthGrid: number[];
  classes: string[];
  alphabet: string;
  bubbleLevels: number[];
  tables: Record<string, NashPushFoldV2Table>;
};

export const NASH_PUSH_FOLD_V2: NashPushFoldV2Data = ${JSON.stringify(data, null, 2)};
`);
