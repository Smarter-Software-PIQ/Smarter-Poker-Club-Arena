const SUITS: Record<string, CardSuit> = { c: 'clubs', d: 'diamonds', h: 'hearts', s: 'spades' };
const STAGES: Record<string, string> = { p: 'preflop', f: 'flop', t: 'turn', r: 'river' };
const ORIGINS: Record<string, string> = { f: 'forced', h: 'horse_policy', p: 'player' };

export const strongHandCards = (text: string): Card[] =>
  (text.match(/../g) ?? []).map((x) => ({ rank: x[0] as CardRank, suit: SUITS[x[1]] }));

/** A recorded decision as a complaint fixture plus the node of the decision. */
export function expandStrongHand(r: RecordedStrongHand): {
  fx: ComplaintFixture;
  node: ComplaintAction;
} {
  const actions: ComplaintAction[] = r.a.split(';').map((row, i) => {
    const [seat, stage, action, amount, origin, full, dead] = row.split('|');
    return {
      ord: i + 1,
      seat: Number(seat),
      stage: STAGES[stage],
      action,
      amount: Number(amount),
      ...(ORIGINS[origin] ? { origin: ORIGINS[origin] } : {}),
      isFullRaise: full === '1',
      dead: dead === '1',
    };
  });
  const node = actions.find((x) => x.ord === r.ord)!;
  if (node.seat !== r.seat || node.action !== r.did || node.stage !== 'river')
    throw new Error(`hand ${r.h}: action ${r.ord} is not the recorded river ${r.did}`);
  const [cap, headsUpCap, feeBB] = r.rake;
  node.publicNode = {
    pot: r.pot,
    ante: r.ante,
    anteType: r.anteType,
    mode: 'cash',
    asset: 'chips',
    seats: r.seats,
    boards: [r.board],
    street: 'river',
    toCall: r.toCall,
    currentBet: r.cur,
    minRaiseTo: r.min,
    maxRaiseTo: r.max,
    legalActions: r.legal,
    dealerSeat: r.dealer,
    chipUnit: 0.01,
    bigBlind: r.bb,
    smallBlind: r.sb,
    variant: r.variant,
    structure: 'pot_limit',
    actorSeat: r.seat,
    bombPot: false,
    boardCount: 1,
    allInOrFold: false,
    fixedBetSize: null,
    wagersCapped: false,
    deductions: {
      bbj: { feeBB, enabled: true, minPotBB: 10, minPlayersDealt: 3 },
      rake: {
        cap,
        percent: 10,
        noFlopNoDrop: true,
        playerCountCaps: [
          [2, headsUpCap],
          [3, cap],
          [4, cap],
        ],
      },
      rules: 'controller-rake-bbj-v1',
      status: 'captured',
      version: 1,
    },
  } as unknown as ComplaintPublicNode;
  const fx: ComplaintFixture = {
    version: 1,
    slug: `omaha-strong-hand-${r.h}-seat-${r.seat}`,
    title: `Omaha River Decision With A Full House, Study Hand ${r.h}`,
    complaint: 'A Horse with a full house on the river checked, only called, raised or folded',
    handId: r.h,
    fmt: 'cash',
    variant: r.variant,
    players: r.pl.split(' ').map((p) => ({ seat: Number(p[0]), isHorse: p[1] === 'H' })),
    hole: { [String(r.seat)]: strongHandCards(r.hole) },
    actions,
    forbidden: [],
    seeds: [],
  };
  return { fx, node };
}
