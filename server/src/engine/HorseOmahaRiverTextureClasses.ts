/**
 * THE RIVER BETTOR BY BOARD TEXTURE (omahaRiverBettorRangeIsTextureMeasured; PLO-OWNER lead-8 2026-11-27, lane
 * payoff). Pure arithmetic: no telemetry, no opponent memory of its own, no random draw.
 *
 * WHY. omahaFacingBetEv prices a river bettor as "the strongest V share of holdings, every holding equally likely"
 * plus a non-value share (omahaFacingBetPriorIsPeopleMeasured: three regions cut by share). The board never enters
 * the weights, and the regions are cut by SHARE of the holdings left after the Horse's own cards. Two measured
 * consequences (S7/l8-payoff/BUILD.md, shown showdowns Oct 22 to Nov 27, people's bets only):
 *  - People's big river bets sit in the board's top hand category: on an unpaired three-flush board 67% of their
 *    shown bets of 0.6 pot and more are flushes (raises 75%); on a paired board 49% to 87% are full houses or
 *    better. A straight on a flush board, or a flush on a paired board, beats far less of that range than the
 *    pooled regions say: Horses that called with them won 6.5 of 41 against 27% needed.
 *  - A region cut by share refills with the next-best holdings when the Horse holds the cards of the best ones,
 *    so a blocker never thins the bettor's value range.
 *
 * THE PRICE. The bettor's holdings are put in five ABSOLUTE classes of this board (score cuts that do not depend on
 * the Horse's hand): A the hands of the board's key category that no other two cards beat inside it, and anything above it; B the key category below that (paired board: full house or better;
 * three-flush board: flush; otherwise straight when one is possible, else three of a kind); C the two categories
 * under the key one; D the category under those; E everything weaker (never cut below one pair). People's shown river bets give the weight of each
 * class by texture, size bucket and bet-or-raise (HorseOmahaRiverTextureClasses.data.ts, generated by
 * server/scripts/omaha-river-texture-classes-fit.ts; the bettor is a person, his cards were shown at showdown; Horse
 * bets, mucked cards and the HUD '*' rows never enter). Evidence order: the bettor's own shown bets (the ratio
 * omahaFacingBetPeoplePrior computes moves the weakest class) -> the texture cell of people -> people pooled over
 * textures -> the balanced share for the price (HorseOmahaEquilibriumAnchor), each behind
 * OMAHA_RIVER_TEXTURE_ANCHOR_BETS pseudo-bets.
 * The verdict (HorseOmahaFacingBetEv) multiplies each class weight by the exact share of that class's holdings the
 * Horse's own cards leave (class share after the Horse's cards over class share on the board alone), so a hand
 * that holds the nut-flush card removes the nut flush from his range and a hand that does not keeps it there: one
 * formula, no hand-class rule, every answer a price.
 * Identity never enters: the same arithmetic for every bettor; only the data is people-only.
 */
import type { Card } from '../types.js';
import {
  omahaBetSizeBucket,
  omahaRiverBoardBands,
  type OmahaRiverBoardScores,
} from './HorseOmahaFacingBetEv.js';
import { OMAHA_RIVER_TEXTURE_CLASSES_DATA } from './HorseOmahaRiverTextureClasses.data.js';

/** Pseudo-bets behind each step of the evidence order (the people prior's anchor weight). */
export const OMAHA_RIVER_TEXTURE_ANCHOR_BETS = 30;
/** The weakest class is never priced above this share, whatever his record (the people prior's cap). */
export const OMAHA_RIVER_TEXTURE_MAX_WEAK = 0.65;

export type OmahaRiverTexture = 'flushPaired' | 'paired' | 'flushEarly' | 'flushRiver' | 'plain';
export type OmahaRiverTextureBucket = 'mid' | 'big' | 'raise';
const CAT = 0x100000;
/** The number of classes (A to E). */
const CLASSES = 5;
const CAT_FULL_HOUSE = 7;
const CAT_FLUSH = 6;
const CAT_STRAIGHT = 5;
const CAT_TRIPS = 4;
const CAT_PAIR = 2;

/**
 * The texture of a five-card board (flop, turn, river in order). An unpaired three-flush board is read apart by
 * WHEN the third card of the suit came: by the turn (flushEarly: a river bet is a bet with the flush already out
 * for a street) or on the river (flushRiver). People's shown big river bets are the nut flush 15 of 26 times in
 * the first case and 14 of 43 in the second.
 */
export function omahaRiverTextureOf(board: Card[]): OmahaRiverTexture | null {
  if (!Array.isArray(board) || board.length !== 5) return null;
  const suits = new Map<string, number>();
  const ranks = new Map<string, number>();
  for (const c of board) {
    if (!c) return null;
    suits.set(c.suit, (suits.get(c.suit) ?? 0) + 1);
    ranks.set(c.rank, (ranks.get(c.rank) ?? 0) + 1);
  }
  const flush = [...suits.values()].some((n) => n >= 3);
  const paired = [...ranks.values()].some((n) => n >= 2);
  if (paired) return flush ? 'flushPaired' : 'paired';
  if (!flush) return 'plain';
  const turn = new Map<string, number>();
  for (const c of board.slice(0, 4)) turn.set(c.suit, (turn.get(c.suit) ?? 0) + 1);
  return [...turn.values()].some((n) => n >= 3) ? 'flushEarly' : 'flushRiver';
}

/** The key category of a texture, given the best score possible on the board. */
export function omahaRiverTextureKeyCategory(texture: OmahaRiverTexture, nutScore: number): number {
  if (texture === 'flushPaired' || texture === 'paired') return CAT_FULL_HOUSE;
  if (texture === 'flushEarly' || texture === 'flushRiver') return CAT_FLUSH;
  return nutScore >= CAT_STRAIGHT * CAT ? CAT_STRAIGHT : CAT_TRIPS;
}

/**
 * The four score cuts between the five classes, strongest first. Class A is every hand of the key category that
 * no other two cards beat inside that category (every ace-high flush, the nut straight, the top full house) and
 * everything above the category.
 */
export function omahaRiverTextureCuts(
  texture: OmahaRiverTexture,
  scores: OmahaRiverBoardScores
): number[] {
  const nut = scores.best(Infinity);
  const k = omahaRiverTextureKeyCategory(texture, nut);
  const top = scores.unbeaten(k * CAT, (k + 1) * CAT);
  const nutCut = top > 0 ? top : nut;
  const keyCut = Math.min(nutCut, k * CAT);
  const under = Math.min(keyCut, Math.max(CAT_PAIR, k - 2) * CAT);
  return [nutCut, keyCut, under, Math.min(under, Math.max(CAT_PAIR, k - 3) * CAT)];
}

/** The class (0 = A ... 4 = E) of a score on a board with these cuts. */
export function omahaRiverTextureClassOf(score: number, cuts: readonly number[]): number {
  for (let i = 0; i < cuts.length; i++) if (score >= cuts[i]) return i;
  return cuts.length;
}

type Cell = { n: number; w: readonly number[] };

export interface OmahaRiverTextureInput {
  board: Card[];
  holeCount: number;
  /** the wager as a share of the pot before it, and whether it is a raise */
  potFrac: number;
  isRaise: boolean;
  /** the balanced non-value share for the price (HorseOmahaEquilibriumAnchor) */
  balanced: number;
  /** his own shown bets: his not-value rate over people's (omahaPeoplePriorShare: share / prior); 1 with no record */
  recordRatio: number;
}
export interface OmahaRiverTextureClasses {
  texture: OmahaRiverTexture;
  bucket: OmahaRiverTextureBucket;
  cuts: number[];
  weights: number[];
  boardShare: number[];
  /** people's shown bets in the texture cell */
  n: number;
}

/** The measured class weights for this bet, or null where nothing is measured (a bet under 0.4 pot, a bad board). */
export function omahaRiverTextureClasses(
  input: OmahaRiverTextureInput
): OmahaRiverTextureClasses | null {
  if (!Number.isFinite(input.potFrac) || !Number.isFinite(input.balanced)) return null;
  const size = omahaBetSizeBucket(input.potFrac);
  if (!input.isRaise && size === 'under40') return null;
  const bucket: OmahaRiverTextureBucket = input.isRaise ? 'raise' : size === 'mid' ? 'mid' : 'big';
  const texture = omahaRiverTextureOf(input.board);
  if (!texture) return null;
  const bands = omahaRiverBoardBands(input.board, input.holeCount, (best) =>
    omahaRiverTextureCuts(texture, best)
  );
  if (!bands) return null;
  const pooled = OMAHA_RIVER_TEXTURE_CLASSES_DATA.pooled[bucket] as Cell;
  const cell = OMAHA_RIVER_TEXTURE_CLASSES_DATA.cells[texture][bucket] as Cell;
  if (!pooled || !(pooled.n > 0) || pooled.w.length !== CLASSES) return null;
  const K = OMAHA_RIVER_TEXTURE_ANCHOR_BETS;
  const b = Math.max(0.02, Math.min(OMAHA_RIVER_TEXTURE_MAX_WEAK, input.balanced));
  // the balanced anchor: the weakest class at the balanced share, the rest split as people split their value
  const W = CLASSES - 1;
  const value = pooled.w.slice(0, W).reduce((x, y) => x + y, 0);
  const eq =
    value > 0
      ? [...pooled.w.slice(0, W).map((x) => ((1 - b) * x) / value), b]
      : [1 - b, ...new Array<number>(W - 1).fill(0), b];
  const blend = (c: Cell | undefined, behind: number[]): number[] =>
    c && c.n > 0 && c.w.length === CLASSES
      ? behind.map((x, i) => (c.n * c.w[i] + K * x) / (c.n + K))
      : behind;
  const w = blend(cell, blend(pooled, eq));
  // his own record moves the weakest class; the others keep their split
  const ratio = Number.isFinite(input.recordRatio) && input.recordRatio > 0 ? input.recordRatio : 1;
  const weak = Math.max(0, Math.min(OMAHA_RIVER_TEXTURE_MAX_WEAK, w[W] * ratio));
  const strong = w.slice(0, W).reduce((x, y) => x + y, 0);
  const weights =
    strong > 0
      ? [...w.slice(0, W).map((x) => (x / strong) * (1 - weak)), weak]
      : [...new Array<number>(W).fill(0), 1];
  return {
    texture,
    bucket,
    cuts: bands.cuts,
    weights,
    boardShare: bands.share,
    n: cell && cell.n > 0 ? cell.n : 0,
  };
}
