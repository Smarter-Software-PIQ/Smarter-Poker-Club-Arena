export function facingShovePrice(
  currentBet: number,
  posted: number,
  players: readonly { bet: number; is_all_in?: boolean; is_folded?: boolean }[]
): boolean {
  return (
    currentBet > posted && players.some((p) => p.is_all_in && !p.is_folded && p.bet >= currentBet)
  );
}
