/**
 * THE PEOPLE-MEASURED BETTOR PRIOR (omahaFacingBetPriorIsPeopleMeasured; PLO-OWNER lead-7 2026-11-26).
 * Pure arithmetic: no telemetry, no opponent memory of its own (the caller passes the bettor's record), no draw.
 *
 * OWNER ORDER 2026-11-26: "the stats need to be used against human players, not horses."
 *
 * WHY. omahaFacingBetEv prices a bettor as a value region plus a non-value share q. Today q comes from
 * OMAHA_EV_PRIOR_BLUFF, a constant fitted on 41 to 179 hands of Nov 10 to 15 (turn 0.22 at 0.7 pot and over, river
 * 0.13 to 0.19, raises 0.08 / 0.15), then moved by public reads measured against the HORSE mean. On the turn that
 * constant is far below what people actually do (people's big heads-up turn bets: 0.39 non-value, n 297), and the
 * reads against the Horse mean compare a bettor with players who almost never bluff. Both push the Horse to fold.
 *
 * THE PRIOR, IN ORDER OF EVIDENCE.
 *  1. His own shown bets of this street, size and line (HorseOmahaBetRead's per-opponent cell): the record counts a
 *     shown bet as value when it beats OMAHA_BET_READ_VALUE_BEATS (80%) of holdings, a different unit from the
 *     price's value region. So the record is compared with PEOPLE'S share of shown bets in that same unit
 *     (nonTop20 in the data): his not-value rate, a Beta-binomial mean with OMAHA_PEOPLE_PRIOR_RECORD_BETS
 *     pseudo-bets at people's rate, over people's rate, multiplies step 2's non-value share (and the river's
 *     non-core share). His record dominates as it grows. A raise has no per-opponent record cell; step 2 only.
 *  2. The PEOPLE-ONLY population share for this street, size bucket and heads-up / multiway, measured from people's
 *     bets that were called and shown at showdown (HorseOmahaFacingBetPeoplePrior.data.ts, generated by
 *     server/scripts/omaha-facing-bet-people-prior-fit.ts; Horse bets, Horse responses, mucked cards and the HUD
 *     '*' population rows never enter; the law anOmahaFacingBetPriorIsPeopleMeasured checks the filters). A called
 *     river bettor is always shown on this platform (7 days: 0 of 106 called person river bettors mucked), so the
 *     shown sample is not biased against bluffs by mucking; the caller's decision does not see the bettor's cards.
 *  3. The balanced share for the price, only as weight behind a thin people cell: q0 = (n x people + K x balanced)
 *     / (n + K), K = OMAHA_PEOPLE_PRIOR_ANCHOR_BETS. A cell with no people measurement is the balanced share.
 *  RIVER REGIONS. On the river people's shown bets are measured on three regions of holdings (riverRegions: core =
 *  the value region, middle = between it and the weakest half, bottom = the weakest half). People's big heads-up river
 *  bets are 55% core, 22% middle, 22% bottom (n 156): today's verdict counts the middle as value, so a hand that
 *  beats the middle folds. The regions go to the verdict (OmahaFacingBetEvRead.pricedRegions), blended toward the
 *  balanced split (core 1 - b, bottom b) by the same n weight; his own record moves the non-core share and keeps
 *  the middle : bottom split.
 * Identity never enters: the same arithmetic for every bettor; only the data is people-only.
 */
import { OMAHA_FACING_BET_PEOPLE_PRIOR_DATA } from './HorseOmahaFacingBetPeoplePrior.data.js';
import { omahaBetSizeBucket } from './HorseOmahaFacingBetEv.js';
import { omahaEquilibriumAnchor } from './HorseOmahaEquilibriumAnchor.js';
import { omahaRiverFrequencyPrior } from './HorseOmahaRiverFrequencyPrior.js';
import {
  omahaPeoplePriorHiddenCell,
  omahaPeoplePriorHiddenFraction,
  type OmahaPeoplePriorHiddenKey,
} from './HorseOmahaPeoplePriorHidden.js';

/** Pseudo-bets of the balanced share behind a people cell (a cell of 150 people bets is 83% people). */
export const OMAHA_PEOPLE_PRIOR_ANCHOR_BETS = 30;
/** Pseudo-bets of the people share behind his own shown bets (OMAHA_EV_SIZE_READ_PRIOR). */
export const OMAHA_PEOPLE_PRIOR_RECORD_BETS = 8;
export const OMAHA_PEOPLE_PRIOR_MIN = 0.02;
export const OMAHA_PEOPLE_PRIOR_MAX = 0.65;

export interface OmahaPeoplePriorInput {
  street: 'turn' | 'river';
  potFrac: number;
  isRaise: boolean;
  /** two or more opponents besides the deciding Horse at the decision (multiway cell) */
  multiway: boolean;
  /** chips the call puts in, and the chips it can win */
  paid: number;
  winnable: number;
  rake: number;
  /** a turn bet with a river bet still to come */
  twoStreet: boolean;
  /** his own shown bets of this street, size and line, or null (always null for a raise) */
  record: { shown: number; value: number } | null;
  /** omahaPeoplePriorCountsHiddenBets: the game and split whose hidden-corrected cell replaces the pooled one (turn
   *  only; null / absent: today's cells, unchanged). The caller then passes a record that counts his hidden bets. */
  hidden?: OmahaPeoplePriorHiddenKey | null;
  /** omahaHiddenBetsArePricedAsGiveUps (with `hidden`, a turn bet): also return the give-up share (giveUp) */
  giveUps?: boolean;
  /** omahaRiverBetPriorReadsHisFrequency (river bet only): his public heads-up unopened river first-bet record; the
   *  non-value share it implies replaces people's as the prior mean of his shown record (absent / null: unchanged) */
  frequency?: { bets: number; opps: number } | null;
}
export interface OmahaPeoplePriorShare {
  /** the non-value share priced */
  share: number;
  /** the people-only population share of the cell (null: not measured) and its n */
  people: number | null;
  peopleN: number;
  /** the balanced share for this price */
  balanced: number;
  /** step 2's share, before his record */
  prior: number;
  /** his shown bets read (0 with no record) */
  shown: number;
  /** river only: the weights on the verdict's three regions (sum 1), null when not measured or on the turn */
  regions: { core: number; middle: number; bottom: number } | null;
  /** omahaHiddenBetsArePricedAsGiveUps, turn only: the part of `share` that is the give-up class (people's hidden
   *  bets of the cell, the balanced share behind a thin cell as the river's bottom region takes it, moved by his own
   *  record with the rest of the share); absent when not asked or not measured */
  giveUp?: number;
}

type Cell = { n: number; share: number | null };
const clamp = (q: number): number =>
  Math.max(OMAHA_PEOPLE_PRIOR_MIN, Math.min(OMAHA_PEOPLE_PRIOR_MAX, q));

/** The people-only cell for this bet: n 0 when not measured. 'over' (above 1.1 pot) reads the 'big' cell. */
export function omahaPeoplePriorCell(
  street: 'turn' | 'river',
  potFrac: number,
  isRaise: boolean,
  multiway: boolean,
  hidden?: OmahaPeoplePriorHiddenKey | null
): Cell {
  if (hidden) {
    const h = omahaPeoplePriorHiddenCell(
      street,
      multiway,
      isRaise ? 'raise' : omahaBetSizeBucket(potFrac),
      hidden
    );
    if (h) return h.share === null ? { n: 0, share: null } : { n: h.n, share: h.share };
  }
  const table = OMAHA_FACING_BET_PEOPLE_PRIOR_DATA.bluff[street][multiway ? 'mw' : 'hu'] as Record<
    string,
    Cell
  >;
  const b = isRaise ? 'raise' : omahaBetSizeBucket(potFrac);
  const cell = table[b === 'over' ? 'big' : b];
  if (!cell || !(cell.n > 0) || cell.share === null || !Number.isFinite(cell.share))
    return { n: 0, share: null };
  return { n: cell.n, share: cell.share };
}

type RegCell = { n: number; core: number | null; middle: number | null; bottom: number | null };

/** The people-only river region cell: null when not measured. */
export function omahaPeopleRiverRegionCell(
  potFrac: number,
  isRaise: boolean,
  multiway: boolean
): { n: number; core: number; middle: number; bottom: number } | null {
  const table = OMAHA_FACING_BET_PEOPLE_PRIOR_DATA.riverRegions[multiway ? 'mw' : 'hu'] as Record<
    string,
    RegCell
  >;
  const b = isRaise ? 'raise' : omahaBetSizeBucket(potFrac);
  const c = table[b === 'over' ? 'big' : b];
  if (!c || !(c.n > 0) || c.core === null || c.middle === null || c.bottom === null) return null;
  return { n: c.n, core: c.core, middle: c.middle, bottom: c.bottom };
}

/** People's share of shown bets in the record's not-value unit for this cell (null: not measured). */
export function omahaPeopleNonTop20(
  street: 'turn' | 'river',
  potFrac: number,
  isRaise: boolean,
  multiway: boolean,
  hidden?: OmahaPeoplePriorHiddenKey | null
): number | null {
  if (hidden) {
    const h = omahaPeoplePriorHiddenCell(
      street,
      multiway,
      isRaise ? 'raise' : omahaBetSizeBucket(potFrac),
      hidden
    );
    if (h) return h.nonTop20;
  }
  const table = OMAHA_FACING_BET_PEOPLE_PRIOR_DATA.nonTop20[street][
    multiway ? 'mw' : 'hu'
  ] as Record<string, Cell>;
  const b = isRaise ? 'raise' : omahaBetSizeBucket(potFrac);
  const c = table[b === 'over' ? 'big' : b];
  if (!c || !(c.n > 0) || c.share === null || !(c.share > 0) || !(c.share < 1)) return null;
  return c.share;
}

/** Step 3 behind step 2: the people cell blended toward the balanced share by its n (the balanced share alone
 *  with no measurement). One function for the turn, the river and the flop. */
function omahaPeoplePriorBlend(cell: Cell, balanced: number): number {
  return cell.share === null
    ? balanced
    : clamp(
        (cell.n * cell.share + OMAHA_PEOPLE_PRIOR_ANCHOR_BETS * balanced) /
          (cell.n + OMAHA_PEOPLE_PRIOR_ANCHOR_BETS)
      );
}

/** Step 1: his not-value rate in the record's own unit over people's rate in that unit (1 with no record). */
function omahaPeoplePriorRecordRatio(
  rec: { shown: number; value: number } | null,
  pNT: number | null,
  priorMean?: number
): { ratio: number; shown: number } {
  const shown = rec && pNT !== null && Number.isFinite(rec.shown) && rec.shown > 0 ? rec.shown : 0;
  // omahaRiverBetPriorReadsHisFrequency: the prior mean of his record is his frequency's share, not people's
  const m = priorMean !== undefined && pNT !== null ? priorMean : pNT;
  if (!(shown > 0)) return { ratio: m !== null && pNT !== null ? m / pNT : 1, shown: 0 };
  const value = Math.max(0, Math.min(shown, Number.isFinite(rec!.value) ? rec!.value : 0));
  return {
    ratio:
      (OMAHA_PEOPLE_PRIOR_RECORD_BETS * m! + (shown - value)) /
      (OMAHA_PEOPLE_PRIOR_RECORD_BETS + shown) /
      pNT!,
    shown,
  };
}

/** The share priced against this bettor: his record over the people cell over the balanced share. */
export function omahaPeoplePriorShare(input: OmahaPeoplePriorInput): OmahaPeoplePriorShare | null {
  if (input.street !== 'turn' && input.street !== 'river') return null;
  if (!Number.isFinite(input.potFrac)) return null;
  const balanced = omahaEquilibriumAnchor(input.paid, input.winnable, input.rake, input.twoStreet);
  if (balanced === null) return null;
  const cell = omahaPeoplePriorCell(
    input.street,
    input.potFrac,
    input.isRaise,
    input.multiway,
    input.hidden
  );
  const prior = omahaPeoplePriorBlend(cell, balanced);
  // river: the blended region weights (core, middle, bottom) before his record
  let base: { core: number; middle: number; bottom: number } | null = null;
  if (input.street === 'river') {
    const rc = omahaPeopleRiverRegionCell(input.potFrac, input.isRaise, input.multiway);
    if (rc) {
      const K = OMAHA_PEOPLE_PRIOR_ANCHOR_BETS;
      const core = (rc.n * rc.core + K * (1 - balanced)) / (rc.n + K);
      const middle = (rc.n * rc.middle) / (rc.n + K);
      const bottom = (rc.n * rc.bottom + K * balanced) / (rc.n + K);
      const t = core + middle + bottom;
      base = { core: core / t, middle: middle / t, bottom: bottom / t };
    }
  }
  const rec = input.isRaise ? null : input.record;
  const pNT = omahaPeopleNonTop20(
    input.street,
    input.potFrac,
    input.isRaise,
    input.multiway,
    input.hidden
  );
  const freq =
    input.frequency && input.street === 'river' && !input.isRaise
      ? omahaRiverFrequencyPrior(input.frequency, pNT)
      : null;
  const { ratio, shown } = omahaPeoplePriorRecordRatio(rec, pNT, freq ? freq.nonValue : undefined);
  const share = clamp(prior * ratio);
  let regions: { core: number; middle: number; bottom: number } | null = null;
  if (base) {
    const nonCore0 = base.middle + base.bottom;
    const nonCore = Math.max(0, Math.min(OMAHA_PEOPLE_PRIOR_MAX, nonCore0 * ratio));
    const mShare = nonCore0 > 0 ? base.middle / nonCore0 : 0;
    regions = { core: 1 - nonCore, middle: nonCore * mShare, bottom: nonCore * (1 - mShare) };
  }
  // omahaHiddenBetsArePricedAsGiveUps: the hidden bets of the cell are the give-up class. The balanced pseudo-bets
  // behind a thin cell give up at the ONE-street balanced share b (a balanced two-street bettor is (1-b)^2 value,
  // b(1-b) bluffs that bet the river again, b bluffs that stop: only the last are give-ups). His record moves it
  // with the rest of the share.
  let giveUp: number | undefined;
  if (input.giveUps === true && input.hidden && input.street === 'turn' && !input.isRaise) {
    const hf = omahaPeoplePriorHiddenFraction(
      'turn',
      input.multiway,
      omahaBetSizeBucket(input.potFrac),
      input.hidden
    );
    const one = omahaEquilibriumAnchor(input.paid, input.winnable, input.rake, false);
    if (hf && one !== null && prior > 0) {
      const K = OMAHA_PEOPLE_PRIOR_ANCHOR_BETS;
      const g0 = (hf.n * hf.hidden + K * one) / (hf.n + K);
      giveUp = Math.min(share, (g0 / prior) * share);
    }
  }
  return {
    share,
    people: cell.share,
    peopleN: cell.n,
    balanced,
    prior,
    shown,
    regions,
    ...(giveUp !== undefined ? { giveUp } : {}),
  };
}

// ───────────── the flop (omahaFlopPressureCapIsPriced; PLO-OWNER lead-7 2026-11-26) ─────────────
/**
 * THE FLOP CELLS. The same three steps on the flop, in the flop verdict's value unit: a person's shown flop bet is
 * non-value when it lies outside the strongest OMAHA_FLOP_EV_VALUE_SHARE x line of holdings on the flop
 * (HorseOmahaFlopFacingBetEv; data.flop, same fit, same people-only filters). The bet may have been answered by
 * anyone: a heads-up flop bet answered by a PERSON and shown is too thin to fit alone (data.flop.*.answeredByAPerson,
 * 45 heads-up bets in 30 days), so the bettor side is people-only and the answer side is not filtered. The balanced
 * share is the price's, over the streets still to bet: one on a final call, three with the turn and the river still
 * to come (1 - (1 - b)^3, b the one-street share of omahaEquilibriumAnchor), inside the same bounds.
 */
type FlopCell = { n: number; share: number | null; nonTop20: number | null };
/** The people-only flop cell for this bet ('over' reads 'big'): n 0 when not measured. */
export function omahaPeopleFlopCell(
  potFrac: number,
  isRaise: boolean,
  multiway: boolean,
  hidden?: OmahaPeoplePriorHiddenKey | null
): { n: number; share: number | null; nonTop20: number | null } {
  if (hidden) {
    const h = omahaPeoplePriorHiddenCell(
      'flop',
      multiway,
      isRaise ? 'raise' : omahaBetSizeBucket(potFrac),
      hidden
    );
    if (h) return h;
  }
  const table = OMAHA_FACING_BET_PEOPLE_PRIOR_DATA.flop[multiway ? 'mw' : 'hu'] as Record<
    string,
    FlopCell
  >;
  const b = isRaise ? 'raise' : omahaBetSizeBucket(potFrac);
  const c = table[b === 'over' ? 'big' : b];
  if (!c || !(c.n > 0) || c.share === null || !Number.isFinite(c.share))
    return { n: 0, share: null, nonTop20: null };
  const nt = c.nonTop20 !== null && c.nonTop20 > 0 && c.nonTop20 < 1 ? c.nonTop20 : null;
  return { n: c.n, share: c.share, nonTop20: nt };
}

export interface OmahaFlopPeoplePriorInput {
  potFrac: number;
  isRaise: boolean;
  multiway: boolean;
  paid: number;
  winnable: number;
  rake: number;
  /** no later decision: the whole stack, or nobody left who can bet */
  final: boolean;
  /** his own shown flop bets of this size, or null (always null for a raise) */
  record: { shown: number; value: number } | null;
  /** omahaPeoplePriorCountsHiddenBets: the game and pot type whose hidden-corrected flop cell replaces the pooled one */
  hidden?: OmahaPeoplePriorHiddenKey | null;
}

/** The balanced non-value share of a flop bet: one street on a final call, three otherwise. */
export function omahaFlopBalancedShare(
  paid: number,
  winnable: number,
  rake: number,
  final: boolean
): number | null {
  const b = omahaEquilibriumAnchor(paid, winnable, rake, false);
  if (b === null) return null;
  return clamp(final ? b : 1 - (1 - b) ** 3);
}

/** The flop share priced against this bettor: his record over the people flop cell over the balanced share. */
export function omahaFlopPeoplePriorShare(
  input: OmahaFlopPeoplePriorInput
): OmahaPeoplePriorShare | null {
  if (!Number.isFinite(input.potFrac)) return null;
  const balanced = omahaFlopBalancedShare(input.paid, input.winnable, input.rake, input.final);
  if (balanced === null) return null;
  const cell = omahaPeopleFlopCell(input.potFrac, input.isRaise, input.multiway, input.hidden);
  const prior = omahaPeoplePriorBlend({ n: cell.n, share: cell.share }, balanced);
  const { ratio, shown } = omahaPeoplePriorRecordRatio(
    input.isRaise ? null : input.record,
    cell.nonTop20
  );
  return {
    share: clamp(prior * ratio),
    people: cell.share,
    peopleN: cell.n,
    balanced,
    prior,
    shown,
    regions: null,
  };
}
