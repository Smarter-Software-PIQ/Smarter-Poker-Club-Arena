/**
 * ═══ NASH PUSH/FOLD V2: THE CALL, TEN-HANDED AND ICM (2026-11-07) ═══════
 *
 * V71 (HorseAnteAwarePushFold) gave the folded-to jam a computed table. The
 * other half of the same game, the CALL of that jam, was never read from it:
 * the solver computes every caller's equilibrium range on every round and
 * threw it away, so a horse facing an open-jam called on a strength bar
 * that did not read the jammer's seat, the dead money or the depth. Measured
 * through HorseLogic.decide (live cash Hybrid persona, the production
 * memory_charts_gold rows hydrated, 24 samples per class), a big blind
 * facing a button jam called 5.2% at 10bb and 9.8% at 20bb (cash) and 6.3%
 * (tournament with a big-blind ante), against a chip-EV Nash call of 23.1% /
 * 11.5% and 38.2% / 19.6%; only the big blind against a small-blind jam had
 * a chart (sb_push, the no-ante game). See docs/changelog/2026-11-07-nash-push-fold-v2.md.
 *
 * HorseNashPushFoldV2.data.ts holds, per (players behind the jammer 1..9,
 * dead ante 0/1/2bb, bubble factor 1/1.5/2/3):
 *   - jam:  each class's "jams up to X bb" (V71's form; B = 1 and 1..8
 *           behind reproduce V71 exactly, 9 behind is a ten-handed UTG);
 *   - call: each class's "calls up to X bb" for the caller kinds the model
 *           distinguishes: an unposted seat ('open'), the small blind and
 *           the big blind (first caller only: an earlier caller ignores
 *           overcallers behind him, the classic chart model).
 * B = 1 is the chip-EV equilibrium. B > 1 is hero's best response, with its
 * chip losses weighted B times its gains (the standard push/fold reading of
 * ICM), against the chip-EV equilibrium of everybody else: hero's own risk
 * is repriced and nobody else's is guessed.
 *
 * Generated by server/scripts/nash-push-fold/solve.py --v2 and wrapped by
 * to-ts-v2.mjs; one character per class (alphabet index / 2 = depth in bb,
 * 0 = never). Nothing here reads who a player is: the inputs are the hand,
 * the seat counts, the depth, the dead money and hero's own bubble factor.
 */
import { NASH_PUSH_FOLD_V2 } from './HorseNashPushFoldV2.data.js';

/** The call layer answers a lone open-jam at this effective depth and below. */
export const NASH_V2_CALL_MAX_BB = 20;

export type NashCallerKind = 'open' | 'sb' | 'bb';

const DATA = NASH_PUSH_FOLD_V2;
const ANTES = [0, 1, 2] as const;
const BUBBLES: readonly number[] = DATA.bubbleLevels;
const MAX_BEHIND = 9;
const GRID_STEP = 0.5;
const GRID_MAX = DATA.depthGrid[DATA.depthGrid.length - 1];

const CLASS_INDEX: ReadonlyMap<string, number> = (() => {
  if (!Array.isArray(DATA.classes) || DATA.classes.length !== 169) {
    throw new Error('nash_v2_table_classes');
  }
  const m = new Map<string, number>();
  DATA.classes.forEach((c, i) => m.set(c, i));
  for (let n = 1; n <= MAX_BEHIND; n++)
    for (const a of ANTES)
      for (const b of BUBBLES) {
        const t = DATA.tables[`${n}|${a}|${b}`];
        const kinds = [...(n >= 3 ? ['open'] : []), ...(n >= 2 ? ['sb'] : []), 'bb'];
        if (
          !t ||
          t.jam.length !== 169 ||
          kinds.some((k) => (t.call as Record<string, string>)[k]?.length !== 169)
        ) {
          throw new Error(`nash_v2_table_shape:${n}|${a}|${b}`);
        }
      }
  return m;
})();

function decode(code: string, k: number): number {
  const i = DATA.alphabet.indexOf(code[k]);
  return i < 0 ? 0 : i / 2;
}

function comboCount(cls: string): number {
  return cls.length === 2 ? 6 : cls.endsWith('s') ? 4 : 12;
}

function behindKey(behind: number): number {
  return Math.max(1, Math.min(MAX_BEHIND, Math.round(behind)));
}

/** Bracketing levels and the weight of the upper one. */
function bracket(levels: readonly number[], x: number): [number, number, number] {
  const v = Math.max(levels[0], Math.min(levels[levels.length - 1], Number.isFinite(x) ? x : 0));
  for (let i = 0; i < levels.length - 1; i++) {
    if (v <= levels[i + 1]) {
      const w = (v - levels[i]) / (levels[i + 1] - levels[i]);
      return [levels[i], levels[i + 1], w];
    }
  }
  const last = levels[levels.length - 1];
  return [last, last, 0];
}

/** Bilinear threshold read across the dead ante and the bubble factor. */
function readUpTo(
  k: number,
  behind: number,
  anteBB: number,
  bubble: number,
  pick: (t: (typeof DATA.tables)[string]) => string | undefined
): number | null {
  const n = behindKey(behind);
  const [a0, a1, wa] = bracket(ANTES, anteBB);
  const [b0, b1, wb] = bracket(BUBBLES, bubble);
  let acc = 0;
  for (const [a, w1] of [
    [a0, 1 - wa],
    [a1, wa],
  ] as const)
    for (const [b, w2] of [
      [b0, 1 - wb],
      [b1, wb],
    ] as const) {
      const w = w1 * w2;
      if (w === 0) continue;
      const code = pick(DATA.tables[`${n}|${a}|${b}`]);
      if (!code) return null;
      acc += w * decode(code, k);
    }
  return acc;
}

/** The depth (bb, blind included) up to which `hand` jams folded-to. */
export function nashV2JamUpTo(
  hand: string,
  behind: number,
  anteBB: number,
  bubble = 1
): number | null {
  const k = CLASS_INDEX.get(hand);
  if (k === undefined || !(behind >= 1)) return null;
  return readUpTo(k, behind, anteBB, bubble, (t) => t.jam);
}

/** The depth (bb, blind included) up to which `hand` calls a lone open-jam. */
export function nashV2CallUpTo(
  hand: string,
  jammerBehind: number,
  callerKind: NashCallerKind,
  anteBB: number,
  bubble = 1
): number | null {
  const k = CLASS_INDEX.get(hand);
  if (k === undefined || !(jammerBehind >= 1)) return null;
  const n = behindKey(jammerBehind);
  // The kinds that exist behind this seat: one behind is the big blind only,
  // two behind the small and big blinds.
  const kind: NashCallerKind =
    n === 1 ? 'bb' : n === 2 && callerKind === 'open' ? 'sb' : callerKind;
  return readUpTo(k, n, anteBB, bubble, (t) => (t.call as Record<string, string>)[kind]);
}

/** 1 at or under the threshold, 0 half a blind past it, linear between. */
function probabilityAt(upTo: number, depthBB: number): number {
  if (upTo >= GRID_MAX) return 1;
  return Math.max(0, Math.min(1, (upTo + GRID_STEP - depthBB) / GRID_STEP));
}

export function nashV2JamProbability(args: {
  hand: string | null;
  behind: number;
  depthBB: number;
  anteBB: number;
  bubble?: number;
}): number | null {
  if (!args.hand || !(args.depthBB > 0)) return null;
  const upTo = nashV2JamUpTo(args.hand, args.behind, args.anteBB, args.bubble ?? 1);
  return upTo === null ? null : probabilityAt(upTo, args.depthBB);
}

export function nashV2CallProbability(args: {
  hand: string | null;
  jammerBehind: number;
  callerKind: NashCallerKind;
  depthBB: number;
  anteBB: number;
  bubble?: number;
}): number | null {
  if (!args.hand || !(args.depthBB > 0)) return null;
  const upTo = nashV2CallUpTo(
    args.hand,
    args.jammerBehind,
    args.callerKind,
    args.anteBB,
    args.bubble ?? 1
  );
  return upTo === null ? null : probabilityAt(upTo, args.depthBB);
}

/** Combo-weighted jam share (0..100), for tests and the audit. */
export function nashV2JamWidth(
  behind: number,
  depthBB: number,
  anteBB: number,
  bubble = 1
): number {
  let w = 0;
  for (const cls of DATA.classes) {
    w +=
      (nashV2JamProbability({ hand: cls, behind, depthBB, anteBB, bubble }) ?? 0) * comboCount(cls);
  }
  return (100 * w) / 1326;
}

/** Combo-weighted call share (0..100), for tests and the audit. */
export function nashV2CallWidth(
  jammerBehind: number,
  callerKind: NashCallerKind,
  depthBB: number,
  anteBB: number,
  bubble = 1
): number {
  let w = 0;
  for (const cls of DATA.classes) {
    w +=
      (nashV2CallProbability({ hand: cls, jammerBehind, callerKind, depthBB, anteBB, bubble }) ??
        0) * comboCount(cls);
  }
  return (100 * w) / 1326;
}
