/**
 * ═══ NASH PUSH/FOLD V2: THE CALL, TEN-HANDED AND ICM (2026-11-07) ═══════
 *
 * V71 (HorseAnteAwarePushFold) gave the folded-to jam a computed table. The
 * other half of the same game, the CALL of that jam, was never read from it:
 * the solver computes every caller's equilibrium range on every round and
 * threw it away, so a horse facing an open-jam called on a strength bar
 * that did not read the jammer's seat, the dead money or the depth. Measured
 * through HorseLogic.decide (live cash Hybrid persona, the production
 * memory_charts_gold rows hydrated, 24 samples per class), a big blind
 * facing a button jam called 5.2% at 10bb and 9.8% at 20bb (cash) and 6.3%
 * (tournament with a big-blind ante), against a chip-EV Nash call of 23.1% /
 * 11.5% and 38.2% / 19.6%; only the big blind against a small-blind jam had
 * a chart (sb_push, the no-ante game). See docs/changelog/2026-11-07-nash-push-fold-v2.md.
 *
 * HorseNashPushFoldV2.data.ts holds, per (players behind the jammer 1..9,
 * dead ante 0/1/2bb, bubble factor 1/1.5/2/3):
 *   - jam:  each class's "jams up to X bb" (V71's form; B = 1 and 1..8
 *           behind reproduce V71 exactly, 9 behind is a ten-handed UTG);
 *   - call: each class's "calls up to X bb" for the caller kinds the model
 *           distinguishes: an unposted seat ('open'), the small blind and
 *           the big blind (first caller only: an earlier caller ignores
 *           overcallers behind him, the classic chart model).
 * B = 1 is the chip-EV equilibrium. B > 1 is hero's best response, with its
 * chip losses weighted B times its gains (the standard push/fold reading of
 * ICM), against the chip-EV equilibrium of everybody else: hero's own risk
 * is repriced and nobody else's is guessed.
 *
 * Generated by server/scripts/nash-push-fold/solve.py --v2 and wrapped by
 * to-ts-v2.mjs; one character per class (alphabet index / 2 = depth in bb,
 * 0 = never). Nothing here reads who a player is: the inputs are the hand,
 * the seat counts, the depth, the dead money and hero's own bubble factor.
 */
import { NASH_PUSH_FOLD_V2 } from './HorseNashPushFoldV2.data.js';

/** The call layer answers a lone open-jam at this effective depth and below. */
export const NASH_V2_CALL_MAX_BB = 20;

export type NashCallerKind = 'open' | 'sb' | 'bb';

const DATA = NASH_PUSH_FOLD_V2;
const ANTES = [0, 1, 2] as const;
const BUBBLES: readonly number[] = DATA.bubbleLevels;
const MAX_BEHIND = 9;
const GRID_STEP = 0.5;
const GRID_MAX = DATA.depthGrid[DATA.depthGrid.length - 1];

const CLASS_INDEX: ReadonlyMap<string, number> = (() => {
  if (!Array.isArray(DATA.classes) || DATA.classes.length !== 169) {
    throw new Error('nash_v2_table_classes');
  }
  const m = new Map<string, number>();
  DATA.classes.forEach((c, i) => m.set(c, i));
  for (let n = 1; n <= MAX_BEHIND; n++)
    for (const a of ANTES)
      for (const b of BUBBLES) {
        const t = DATA.tables[`${n}|${a}|${b}`];
        const kinds = [...(n >= 3 ? ['open'] : []), ...(n >= 2 ? ['sb'] : []), 'bb'];
        if (
          !t ||
          t.jam.length !== 169 ||
          kinds.some((k) => (t.call as Record<string, string>)[k]?.length !== 169)
        ) {
          throw new Error(`nash_v2_table_shape:${n}|${a}|${b}`);
        }
      }
  return m;
})();

function decode(code: string, k: number): number {
  const i = DATA.alphabet.indexOf(code[k]);
  return i < 0 ? 0 : i / 2;
}

function comboCount(cls: string): number {
  return cls.length === 2 ? 6 : cls.endsWith('s') ? 4 : 12;
}

function behindKey(behind: number): number {
  return Math.max(1, Math.min(MAX_BEHIND, Math.round(behind)));
}

/** Bracketing levels and the weight of the upper one. */
function bracket(levels: readonly number[], x: number): [number, number, number] {
  const v = Math.max(levels[0], Math.min(levels[levels.length - 1], Number.isFinite(x) ? x : 0));
  for (let i = 0; i < levels.length - 1; i++) {
    if (v <= levels[i + 1]) {
      const w = (v - levels[i]) / (levels[i + 1] - levels[i]);
      return [levels[i], levels[i + 1], w];
    }
  }
  const last = levels[levels.length - 1];
  return [last, last, 0];
}

/** Bilinear threshold read across the dead ante and the bubble factor. */
function readUpTo(
  k: number,
  behind: number,
  anteBB: number,
  bubble: number,
  pick: (t: (typeof DATA.tables)[string]) => string | undefined
): number | null {
  const n = behindKey(behind);
  const [a0, a1, wa] = bracket(ANTES, anteBB);
  const [b0, b1, wb] = bracket(BUBBLES, bubble);
  let acc = 0;
  for (const [a, w1] of [
    [a0, 1 - wa],
    [a1, wa],
  ] as const)
    for (const [b, w2] of [
      [b0, 1 - wb],
      [b1, wb],
    ] as const) {
      const w = w1 * w2;
      if (w === 0) continue;
      const code = pick(DATA.tables[`${n}|${a}|${b}`]);
      if (!code) return null;
      acc += w * decode(code, k);
    }
  return acc;
}

/** The depth (bb, blind included) up to which `hand` jams folded-to. */
export function nashV2JamUpTo(
  hand: string,
  behind: number,
  anteBB: number,
  bubble = 1
): number | null {
  const k = CLASS_INDEX.get(hand);
  if (k === undefined || !(behind >= 1)) return null;
  return readUpTo(k, behind, anteBB, bubble, (t) => t.jam);
}

/** The depth (bb, blind included) up to which `hand` calls a lone open-jam. */
export function nashV2CallUpTo(
  hand: string,
  jammerBehind: number,
  callerKind: NashCallerKind,
  anteBB: number,
  bubble = 1
): number | null {
  const k = CLASS_INDEX.get(hand);
  if (k === undefined || !(jammerBehind >= 1)) return null;
  const n = behindKey(jammerBehind);
  // The kinds that exist behind this seat: one behind is the big blind only,
  // two behind the small and big blinds.
  const kind: NashCallerKind =
    n === 1 ? 'bb' : n === 2 && callerKind === 'open' ? 'sb' : callerKind;
  return readUpTo(k, n, anteBB, bubble, (t) => (t.call as Record<string, string>)[kind]);
}

/** 1 at or under the threshold, 0 half a blind past it, linear between. */
function probabilityAt(upTo: number, depthBB: number): number {
  if (upTo >= GRID_MAX) return 1;
  return Math.max(0, Math.min(1, (upTo + GRID_STEP - depthBB) / GRID_STEP));
}

export function nashV2JamProbability(args: {
  hand: string | null;
  behind: number;
  depthBB: number;
  anteBB: number;
  bubble?: number;
}): number | null {
  if (!args.hand || !(args.depthBB > 0)) return null;
  const upTo = nashV2JamUpTo(args.hand, args.behind, args.anteBB, args.bubble ?? 1);
  return upTo === null ? null : probabilityAt(upTo, args.depthBB);
}

export function nashV2CallProbability(args: {
  hand: string | null;
  jammerBehind: number;
  callerKind: NashCallerKind;
  depthBB: number;
  anteBB: number;
  bubble?: number;
}): number | null {
  if (!args.hand || !(args.depthBB > 0)) return null;
  const upTo = nashV2CallUpTo(
    args.hand,
    args.jammerBehind,
    args.callerKind,
    args.anteBB,
    args.bubble ?? 1
  );
  return upTo === null ? null : probabilityAt(upTo, args.depthBB);
}

/** Combo-weighted jam share (0..100), for tests and the audit. */
export function nashV2JamWidth(
  behind: number,
  depthBB: number,
  anteBB: number,
  bubble = 1
): number {
  let w = 0;
  for (const cls of DATA.classes) {
    w +=
      (nashV2JamProbability({ hand: cls, behind, depthBB, anteBB, bubble }) ?? 0) * comboCount(cls);
  }
  return (100 * w) / 1326;
}

/** Combo-weighted call share (0..100), for tests and the audit. */
export function nashV2CallWidth(
  jammerBehind: number,
  callerKind: NashCallerKind,
  depthBB: number,
  anteBB: number,
  bubble = 1
): number {
  let w = 0;
  for (const cls of DATA.classes) {
    w +=
      (nashV2CallProbability({ hand: cls, jammerBehind, callerKind, depthBB, anteBB, bubble }) ??
        0) * comboCount(cls);
  }
  return (100 * w) / 1326;
}

/** Evidenced tight-jammer read supplied to nashV2TightJammerParams (2026-11-21). */
export interface NashTightJammerInput {
  /** Shrunk observed open-raise width of the jammer in (0, 1], e.g. from RFI/PFR posterior. */
  observedOpenWidth: number;
  /** Sample-size / credibility / gear-shift confidence in [0, 1]; 0 = unknown or stood down. */
  confidence: number;
}

export interface NashTightJammerParams {
  /** Effective jammer-behind index in [jammerBehind, 9] (fractional for smooth interpolation). */
  effectiveBehind: number;
  /** Effective bubble factor (>= baseBubble, capped so premiums always call). */
  effectiveBubble: number;
  /** True only when the tight read actually moved the call parameters tighter. */
  tightened: boolean;
}

const TIGHT_JAMMER_MIN_OBS_PCT = 3;
const TIGHT_JAMMER_MIN_GAP_PCT = 0.5;
const TIGHT_JAMMER_MAX_ULTRA_BUBBLE_MUL = 2;
/**
 * Short-stack desperation stand-down (poker physics):
 * HorseMind tracks all-depth VPIP/PFR/RFI (dominated by 20-100bb play). At
 * short push/fold depths (<= 10bb or Harrington M <= 4, where dead money per
 * orbit is >= 25% of the effective stack), even tight regulars shove far wider
 * than their deep-stack average RFI and pot odds make over-folding expensive.
 * Ramp smoothly from exact Nash at <= 10bb / M <= 4 to full tight-jammer
 * respect at voluntary open-jam depths (>= 13bb and M >= 5.5).
 */
const TIGHT_JAMMER_STAND_DOWN_DEPTH_BB = 10;
const TIGHT_JAMMER_FULL_DEPTH_BB = 13;
const TIGHT_JAMMER_STAND_DOWN_M = 4;
const TIGHT_JAMMER_FULL_M = 5.5;

/**
 * Tighten a nashCallVsJam lookup when the lone open-jammer has an evidenced
 * tight/nit read (shrunk by sample size, gear-shift release, and short-stack
 * desperation stand-down).
 *
 * Maps the credibility-blended jammer range width onto the already-solved
 * HorseNashPushFoldV2 caller table (n = jammerBehind..9, whose equilibrium jam
 * widths span ~66% down to ~6-10%), and only applies a bounded extra bubble
 * factor (<= 2x) when the target width is even tighter than a 10-handed UTG
 * jammer (n = 9). Returns exact unchanged parameters when the jammer is
 * unknown, confidence is 0, depth/M is in the short-stack desperation zone, or
 * observedOpenWidth >= the seat's Nash jam width.
 */
export function nashV2TightJammerParams(args: {
  jammerBehind: number;
  depthBB: number;
  anteBB: number;
  bubble?: number;
  tightRead: NashTightJammerInput | null | undefined;
}): NashTightJammerParams {
  const nStart = behindKey(args.jammerBehind);
  const baseBubble = args.bubble ?? 1;
  const r = args.tightRead;
  if (
    !r ||
    !Number.isFinite(r.confidence) ||
    !(r.confidence > 0) ||
    !Number.isFinite(r.observedOpenWidth)
  ) {
    return { effectiveBehind: nStart, effectiveBubble: baseBubble, tightened: false };
  }
  const orbitCostBB = 1.5 + Math.max(0, Number.isFinite(args.anteBB) ? args.anteBB : 0);
  const mRatio = args.depthBB / orbitCostBB;
  const depthWeight = Math.max(
    0,
    Math.min(
      1,
      (args.depthBB - TIGHT_JAMMER_STAND_DOWN_DEPTH_BB) /
        (TIGHT_JAMMER_FULL_DEPTH_BB - TIGHT_JAMMER_STAND_DOWN_DEPTH_BB)
    )
  );
  const mWeight = Math.max(
    0,
    Math.min(
      1,
      (mRatio - TIGHT_JAMMER_STAND_DOWN_M) / (TIGHT_JAMMER_FULL_M - TIGHT_JAMMER_STAND_DOWN_M)
    )
  );
  const stackWeight = Math.min(depthWeight, mWeight);
  if (!(stackWeight > 0)) {
    return { effectiveBehind: nStart, effectiveBubble: baseBubble, tightened: false };
  }
  const k = Math.max(0, Math.min(1, r.confidence)) * stackWeight;
  const obsPct = Math.max(TIGHT_JAMMER_MIN_OBS_PCT, Math.min(100, r.observedOpenWidth * 100));
  const nashPct = nashV2JamWidth(nStart, args.depthBB, args.anteBB, 1);
  if (!(obsPct < nashPct - TIGHT_JAMMER_MIN_GAP_PCT)) {
    return { effectiveBehind: nStart, effectiveBubble: baseBubble, tightened: false };
  }
  const targetPct = nashPct - k * (nashPct - obsPct);
  let prevN = nStart;
  let prevW = nashPct;
  for (let n = nStart + 1; n <= MAX_BEHIND; n++) {
    const w = nashV2JamWidth(n, args.depthBB, args.anteBB, 1);
    if (targetPct >= w) {
      const span = prevW - w;
      const frac = span > 1e-6 ? Math.max(0, Math.min(1, (prevW - targetPct) / span)) : 1;
      return {
        effectiveBehind: prevN + frac,
        effectiveBubble: baseBubble,
        tightened: true,
      };
    }
    prevN = n;
    prevW = w;
  }
  // Tighter than a 10-handed UTG Nash jammer (n = 9): hold n = 9 and apply a
  // bounded bubble multiplier (at most 2x, within the table's max bubble level).
  const maxBubble = BUBBLES[BUBBLES.length - 1];
  const ultraMul = Math.max(
    1,
    Math.min(
      TIGHT_JAMMER_MAX_ULTRA_BUBBLE_MUL,
      prevW / Math.max(TIGHT_JAMMER_MIN_OBS_PCT, targetPct)
    )
  );
  const effectiveBubble = Math.min(maxBubble, baseBubble * ultraMul);
  return {
    effectiveBehind: MAX_BEHIND,
    effectiveBubble,
    tightened: MAX_BEHIND > nStart || effectiveBubble > baseBubble + 1e-9,
  };
}

/**
 * Call probability against a lone open-jam with optional tight-jammer respect.
 * Identical to nashV2CallProbability when tightRead is null or does not tighten.
 */
export function nashV2TightJammerCallProbability(args: {
  hand: string | null;
  jammerBehind: number;
  callerKind: NashCallerKind;
  depthBB: number;
  anteBB: number;
  bubble?: number;
  tightRead: NashTightJammerInput | null | undefined;
}): { probability: number | null; tightened: boolean } {
  if (!args.hand || !(args.depthBB > 0)) return { probability: null, tightened: false };
  const adj = nashV2TightJammerParams({
    jammerBehind: args.jammerBehind,
    depthBB: args.depthBB,
    anteBB: args.anteBB,
    bubble: args.bubble,
    tightRead: args.tightRead,
  });
  if (!adj.tightened) {
    return {
      probability: nashV2CallProbability({
        hand: args.hand,
        jammerBehind: args.jammerBehind,
        callerKind: args.callerKind,
        depthBB: args.depthBB,
        anteBB: args.anteBB,
        bubble: args.bubble,
      }),
      tightened: false,
    };
  }
  const n0 = Math.floor(adj.effectiveBehind);
  const n1 = Math.min(MAX_BEHIND, n0 + 1);
  const wn = adj.effectiveBehind - n0;
  const up0 = nashV2CallUpTo(args.hand, n0, args.callerKind, args.anteBB, adj.effectiveBubble);
  if (up0 === null) return { probability: null, tightened: false };
  let upTo = up0;
  if (wn > 0 && n1 !== n0) {
    const up1 = nashV2CallUpTo(args.hand, n1, args.callerKind, args.anteBB, adj.effectiveBubble);
    if (up1 !== null) upTo = (1 - wn) * up0 + wn * up1;
  }
  return { probability: probabilityAt(upTo, args.depthBB), tightened: true };
}
