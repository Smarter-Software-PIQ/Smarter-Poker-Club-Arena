/**
 * Offline compiler for HorseRunItTwicePeople.data.ts (option horseRunItTwiceIsPriced).
 * Pure: rows in, curve out. It never runs inside the engine and reads no database;
 * the rows are people's (never Horses') run-it-twice answers exported from the
 * public action logs (action_audit_logs engine_rit_* joined to the public all-in
 * equity). The SQL, the export and the sha256 of each input live with the option's
 * criteria file (docs/horse-option-authority.d/horseRunItTwiceIsPriced.md).
 */
import { runItTwiceVarianceShare, type RunItTwiceRole } from './HorseRunItTwiceCell.js';
import type { RunItTwicePeopleCurve } from './HorseRunItTwicePeople.data.js';

export interface RunItTwicePeopleRow {
  role: RunItTwiceRole;
  /** 1 = once / declined; 2 = two runs / accepted; 3 = three runs */
  runs: number;
  equity: number;
  potBB: number;
  playersAllIn: number;
}

export const RIT_CURVE_VARIANCE_GRID: readonly number[] = Array.from(
  { length: 21 },
  (_, i) => i / 20
);
export const RIT_CURVE_POT_BB_GRID: readonly number[] = [10, 20, 40, 80, 160, 320, 640];
/** Kernel bandwidths and shrink strength, declared in the criteria file before any replay. */
export const RIT_CURVE_BANDWIDTH_VARIANCE = 0.2;
export const RIT_CURVE_BANDWIDTH_LN_POT = 0.8;
export const RIT_CURVE_SHRINK_STRENGTH = 10;

const round4 = (x: number) => Math.round(x * 10000) / 10000;

export function compileRunItTwicePeopleCurve(
  rows: readonly RunItTwicePeopleRow[],
  meta: { source: string; window: string }
): RunItTwicePeopleCurve {
  const ok = rows.filter(
    (r) =>
      (r.role === 'chooser' || r.role === 'responder') &&
      Number.isFinite(r.equity) &&
      Number.isFinite(r.potBB) &&
      r.potBB > 0 &&
      Number.isFinite(r.runs)
  );
  const lnPotGrid = RIT_CURVE_POT_BB_GRID.map((p) => round4(Math.log(p)));
  const build = (role: RunItTwiceRole) => {
    const mine = ok
      .filter((r) => r.role === role)
      .map((r) => ({
        v: runItTwiceVarianceShare(r.equity, r.playersAllIn),
        lp: Math.log(Math.max(1, r.potBB)),
        multi: r.runs > 1 ? 1 : 0,
        three: r.runs === 3 ? 1 : 0,
      }));
    const n = mine.length;
    const pooledMulti = n ? mine.reduce((s, r) => s + r.multi, 0) / n : 0;
    const multis = mine.filter((r) => r.multi === 1);
    const pooledThree = multis.length ? multis.reduce((s, r) => s + r.three, 0) / multis.length : 0;
    const k = RIT_CURVE_SHRINK_STRENGTH;
    const pMulti: number[][] = [];
    const pThree: number[][] = [];
    const nEff: number[][] = [];
    for (const v of RIT_CURVE_VARIANCE_GRID) {
      const rm: number[] = [];
      const rt: number[] = [];
      const rn: number[] = [];
      for (const lp of lnPotGrid) {
        let w = 0;
        let wy = 0;
        let w3 = 0;
        let w3y = 0;
        for (const r of mine) {
          const kw = Math.exp(
            -0.5 * ((r.v - v) / RIT_CURVE_BANDWIDTH_VARIANCE) ** 2 -
              0.5 * ((r.lp - lp) / RIT_CURVE_BANDWIDTH_LN_POT) ** 2
          );
          w += kw;
          wy += kw * r.multi;
          if (r.multi) {
            w3 += kw;
            w3y += kw * r.three;
          }
        }
        rm.push(round4((wy + k * pooledMulti) / (w + k)));
        rt.push(round4((w3y + k * pooledThree) / (w3 + k)));
        rn.push(Math.round(w * 10) / 10);
      }
      pMulti.push(rm);
      pThree.push(rt);
      nEff.push(rn);
    }
    return {
      n,
      pooledMulti: round4(pooledMulti),
      pooledThree: round4(pooledThree),
      pMulti,
      pThree,
      nEff,
    };
  };
  return {
    version: 1,
    source: meta.source,
    window: meta.window,
    varianceGrid: RIT_CURVE_VARIANCE_GRID.map(round4),
    lnPotGrid,
    roles: { chooser: build('chooser'), responder: build('responder') },
  };
}

/** The data file's text, deterministic for the same rows. */
export function renderRunItTwicePeopleCurveFile(curve: RunItTwicePeopleCurve): string {
  return (
    '/**\n * GENERATED by compileRunItTwicePeopleCurve (HorseRunItTwicePriced, option horseRunItTwiceIsPriced).\n' +
    ' * People only (never Horses), identity-free aggregates. Do not edit by hand: re-run the compiler.\n */\n' +
    'export interface RunItTwicePeopleRoleCurve {\n  readonly n: number;\n  readonly pooledMulti: number;\n  readonly pooledThree: number;\n' +
    '  readonly pMulti: readonly (readonly number[])[];\n  readonly pThree: readonly (readonly number[])[];\n  readonly nEff: readonly (readonly number[])[];\n}\n' +
    'export interface RunItTwicePeopleCurve {\n  readonly version: 1;\n  readonly source: string;\n  readonly window: string;\n' +
    '  readonly varianceGrid: readonly number[];\n  readonly lnPotGrid: readonly number[];\n' +
    '  readonly roles: { readonly chooser: RunItTwicePeopleRoleCurve; readonly responder: RunItTwicePeopleRoleCurve };\n}\n' +
    `export const RUN_IT_TWICE_PEOPLE_CURVE: RunItTwicePeopleCurve = ${JSON.stringify(curve)};\n`
  );
}
